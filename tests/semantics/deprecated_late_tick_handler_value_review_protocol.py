def entered(name, class_name, handler, completion, status, arg_owners):
    replacements = {
        'handler_value24_exception': handler,
        'pexecutortick.COMPLETION = NORMAL': f'pexecutortick.COMPLETION = {completion}',
        'S.SHUTDOWN.COMPLETION = NORMAL': f'S.SHUTDOWN.COMPLETION = {completion}',
        'S.DESTRUCTION.COMPLETION = NORMAL': f'S.DESTRUCTION.COMPLETION = {completion}',
        'S.EXITSTATUS = 0': f'S.EXITSTATUS = {status}',
        '$heap_owners($heap_graph(S), HOBJECT n_arg) = 2':
            f'$heap_owners($heap_graph(S), HOBJECT n_arg) = {arg_owners}',
    }
    checks = [replacements.get(check, check.replace('handler_value24_exception', handler))
              for check in review.CASES[FIRST]['checks']]
    if arg_owners == 3:
        checks[checks.index('$node_children(S, HOBJECT n_returned) = eps')] = (
            '$node_children(S, HOBJECT n_returned) = [HOBJECT n_arg]')
    return {'source': source(name),
            'stage': review.CASES[FIRST]['stage'].replace('HandlerValue24Result', class_name),
            'checks': checks}


