"""The registered current callback keeps the original borrowed header alive."""
import json

from string_offset_request_base_cv_peer_review import HELPERS, seek
from string_offset_undefined_cv_review import guards


def render(program, filename_b64):
    checks = [
        'S_initial = $php_run(' + program + ', 0, ' + json.dumps(filename_b64) + ')',
        'S_initial.COMPLETION = BUDGET',
    ] + seek('S_initial', 0, 'S_before') + [
        'S_before.TODO = (ERROR_HANDLER_INVOKE perrorcall) :: ptask_before*',
        'perrorcall.RESUME = KEY_READ_RESULT pkeyread',
        r'pkeyread.PHASE = KEY_CV /\ pkeyread.VALUE = PNULL',
        'pkeyread.NAME = $ptascii("key")',
        r'pkeyread.INPUT = VARIABLE pkeyread.NAME 18 /\ pkeyread.LINE = 18',
        'pkeyread.BASE = PSTRING_CARRIER (REQUEST_STRING 0) ($ptascii("abc"))',
        'pkeyread.OWNERS = BASE_VALUE (VARIABLE n_base_name* z_base)',
        'n_base_name* = $ptascii("base")',
        '$lookup(S_before.ENV, n_base_name*) = (n_original)',
        r'n_original = 2 /\ S_before.STORE[n_original] = DEFINED pkeyread.BASE',
        '$lookup(S_before.ENV, $ptascii("got")) = (n_got)',
        'n_got = 3',
        '$lookup(S_before.ENV, pkeyread.NAME) = eps',
        'perrorcall.CALLBACK = pkeyread.BASE',
        'S_before.ERRORHANDLER = {CALLBACK (pkeyread.BASE), LEVELS 30719}',
        'S_before.ERRORHANDLERS = [{CALLBACK eps, LEVELS 0}]',
        '$error_call_valid(S_before, perrorcall)',
        'H_before = $heap_graph(S_before)',
        'H_before = {NODES ([HCELL 0, HCELL 1, HCELL 2, HCELL 3]), EDGES eps, ROOTS ([HCELL 3, HCELL 2, HCELL 1, HCELL 0]), DEBTS eps}',
        *guards('S_before'),
    ] + seek('S_before', 1, 'S') + [
        'S.TODO = (KEY_READ_RESULT pkeyread) :: ptask_tail*',
        r'S.COMPLETION = NORMAL /\ S.CURRENT = eps /\ S.FRAMES = eps',
        'S.STORE[n_original] = DEFINED pkeyread.BASE',
        '~((HCELL n_original) <- S.ALLOCATIONS)',
        '$lookup(S.ENV, n_base_name*) = (n_base)',
        '$lookup(S.ENV, pkeyread.NAME) = (n_key)',
        r'n_base = 9 /\ n_key = 10',
        'S.STORE[n_base] = DEFINED (PINT 99)',
        'S.STORE[n_key] = DEFINED (PINT 0)',
        'S.STORE[n_got] = DEFINED (PINT 99)',
        'S.REFCELLS = [n_base]',
        '$call_reference_operand_valid(S, REFERENCE n_base)',
        'S.STRINGDATA = [$ptascii("abc")]',
        'S.ERRORHANDLER = S_before.ERRORHANDLER',
        'S.ERRORHANDLERS = S_before.ERRORHANDLERS',
        '$string_carrier_valid(S, pkeyread.BASE)',
        '$error_handler_callable(S, pkeyread.BASE) = (true)',
        '$error_handler_retained(S, pkeyread.BASE)',
        'pstringread = {READ pkeyread, BASECELL eps, KEYCELL eps, KEYREF false, PHASE STRING_CAST}',
        '$key_read_valid(S, pkeyread)',
        '$string_read_cv_source(S, pstringread)',
        '~$string_read_retained(S, pstringread, S.ENV)',
        '$string_read_callback_has(pkeyread.BASE, S.ERRORHANDLER :: S.ERRORHANDLERS)',
        '$string_read_callback_retained(S, pstringread)',
        '$string_read_provider_ready(S, pstringread)',
        '$string_read_cv_plan(S, pkeyread) = (pstringread)',
        '~$string_read_cv_released(S, pkeyread)',
        '$string_read_key_current(S, pstringread) = (PINT 0)',
        '$string_read_release_cells(S, 0, S.ALLOCATIONS)',
        '~$string_read_release_handlers(S, 0, S.ERRORHANDLER :: S.ERRORHANDLERS)',
        '$error_handler_roots(S.ERRORHANDLER) = eps',
        '$error_handler_stack_roots(S.ERRORHANDLERS) = eps',
        '$task_nodes(KEY_READ_RESULT pkeyread) = eps',
        '$task_nodes(STRING_READ_RESULT pstringread) = eps',
        'H = $heap_graph(S)',
        'H = {NODES ([HCELL 0, HCELL 1, HCELL 3, HCELL 9, HCELL 10]), EDGES eps, ROOTS ([HCELL 10, HCELL 9, HCELL 3, HCELL 1, HCELL 0]), DEBTS eps}',
        *guards('S'),
        'perrorcall_cast = {SITE pkeyread.SITE, LEVEL 2, MESSAGE ($ptascii("String offset cast occurred")), LINE 18, EVENT (DIAGNOSTIC "Warning" ($ptascii("String offset cast occurred")) 18), CALLBACK pkeyread.BASE, TARGET eps, RESUME (STRING_READ_RESULT pstringread)}',
        'PhpStep: S ~> S_dispatch',
        'S_dispatch = S[.TODO = (ERROR_HANDLER_INVOKE perrorcall_cast) :: ptask_tail*][.RESULT = KNOWN PNULL][.BASE = BASE_VALUE (KNOWN PNULL)][.ERRORFATALTRACE = eps]',
        '$error_call_valid(S_dispatch, perrorcall_cast)',
        '$heap_graph(S_dispatch) = H',
        '$drive_steps(S, 0) = S[.COMPLETION = BUDGET]',
        '$drive_steps(S, 1) = S_dispatch[.COMPLETION = BUDGET]',
    ] + seek('S_dispatch', 2, 'S_cast') + [
        'S_cast.TODO = (STRING_READ_RESULT pstringread) :: ptask_tail*',
        r'S_cast.CURRENT = eps /\ S_cast.FRAMES = eps',
        'S_cast.STORE[n_original] = DEFINED pkeyread.BASE',
        '~((HCELL n_original) <- S_cast.ALLOCATIONS)',
        'S_cast.STORE[n_base] = DEFINED (PINT 99)',
        'S_cast.STORE[n_key] = DEFINED (PINT 0)',
        'S_cast.ERRORHANDLER = S.ERRORHANDLER',
        'S_cast.ERRORHANDLERS = S.ERRORHANDLERS',
        '$string_read_source(S_cast, pstringread)',
        '~$string_read_retained(S_cast, pstringread, S_cast.ENV)',
        '$string_read_callback_retained(S_cast, pstringread)',
        '$string_read_provider_ready(S_cast, pstringread)',
        '$string_read_current_offset(S_cast, pstringread, PINT 0) = (0)',
        '$heap_graph(S_cast) = H',
        'S_expected = S_cast[.TODO = ptask_tail*][.RESULT = KNOWN (PSTRING_CARRIER INTERNED_STRING ([97]))][.BASE = BASE_VALUE (KNOWN PNULL)]',
        'PhpStep: S_cast ~> S_after',
        'S_after = S_expected',
        '$heap_graph(S_after) = H',
        'S_after.EVENTS = S_cast.EVENTS',
        '$drive_steps(S_cast, 0) = S_cast[.COMPLETION = BUDGET]',
        '$drive_steps(S_cast, 1) = S_expected[.COMPLETION = BUDGET]',
        *guards('S_after'),
        'S_done = $drive_steps(S_after, 1000)',
        'S_done.COMPLETION = NORMAL',
        '$lookup(S_done.ENV, $ptascii("got")) = (n_got)',
        'S_done.STORE[n_got] = DEFINED (PSTRING_CARRIER INTERNED_STRING ([97]))',
    ]
    derived_start = len(checks)
    checks += [
        # The registered value supplies identity; masks never supply an owner.
        '$string_read_callback_retained(S_cast[.ERRORHANDLER.LEVELS = 0], pstringread)',
        'S_prior = S_cast[.ERRORHANDLER.CALLBACK = (PSTRING_CARRIER INTERNED_STRING ($ptascii("abc")))][.ERRORHANDLERS = [{CALLBACK eps, LEVELS 9}, {CALLBACK (pkeyread.BASE), LEVELS 0}]]',
        '$string_read_callback_retained(S_prior, pstringread)',
        '$string_read_resume(S_prior, pstringread) = S_prior[.TODO = ptask_tail*][.RESULT = S_expected.RESULT][.BASE = S_expected.BASE]',
        # Raw/equal-byte/invalid registry values cannot own this exact header.
        'S_other = S_cast[.STRINGDATA = S_cast.STRINGDATA ++ [$ptascii("abc")]][.ERRORHANDLER.CALLBACK = (PSTRING_CARRIER (REQUEST_STRING 1) ($ptascii("abc")))]',
        '$string_carrier_valid(S_other, PSTRING_CARRIER (REQUEST_STRING 1) ($ptascii("abc")))',
        '~$string_read_callback_retained(S_other, pstringread)',
        '~$string_read_provider_ready(S_other, pstringread)',
        '$string_read_cv_released(S_other, pkeyread)',
        '~$string_read_callback_retained(S_cast[.ERRORHANDLER.CALLBACK = (PSTRING ($ptascii("abc")))], pstringread)',
        '~$string_read_callback_retained(S_cast[.ERRORHANDLER.CALLBACK = (PSTRING_CARRIER (REQUEST_STRING 1) ($ptascii("abc")))], pstringread)',
        '~$string_read_callback_retained(S_cast[.ERRORHANDLER.CALLBACK = (PSTRING_CARRIER (REQUEST_STRING 0) ($ptascii("abd")))], pstringread)',
        '~$string_read_callback_retained(S_cast[.ERRORHANDLER.CALLBACK = eps], pstringread)',
        '~$string_read_callback_retained(S_cast[.FUNCTIONS = eps][.CALLABLES = eps], pstringread)',
        # Each normal source continuation must recheck the current registry.
        '~$string_read_callback_retained(S_dispatch, pstringread)',
        '~$string_read_callback_retained(S_cast[.TODO = ptask_tail*], pstringread)',
        '~$string_read_callback_retained(S_cast[.COMPLETION = BUDGET], pstringread)',
        '~$string_read_callback_retained(S_cast[.COMPLETION = EXITED 0], pstringread)',
        'S_pending = S_cast[.TODO = (THROW_SEARCH 0) :: ptask_tail*]',
        '~$string_read_callback_retained(S_pending, pstringread)',
        '~$string_read_provider_ready(S_pending, pstringread)',
        '$string_read_discard(S_pending, pstringread) = S_pending[.COMPLETION = UNSUPPORTED "string offset borrowed carrier after callback"]',
        '~$string_read_callback_retained(S_cast, pstringread[.PHASE = STRING_LEADING 0])',
        '~$string_read_callback_retained(S_cast, pstringread[.PHASE = STRING_BOUNDS 8])',
        '~$string_read_callback_retained(S_cast, pstringread[.READ.PHASE = KEY_NULL])',
        '~$string_read_callback_retained(S_cast, pstringread[.BASECELL = (n_base)])',
        '~$string_read_callback_retained(S_cast, pstringread[.KEYCELL = (n_key)])',
    ]
    for field in ('ORIGIN', 'SOURCES', 'CODE', 'STRINGDATA'):
        checks.append('~$string_read_callback_retained(S_cast[.' + field + ' = eps], pstringread)')
    return (HELPERS + '\ndec $main() : bool\ndef $main() = true\n' + ''.join(
        '  -- ' + (check if check.startswith('PhpStep:') else 'if ' + check) + '\n'
        for check in checks), len(checks), len(checks) - derived_start)
