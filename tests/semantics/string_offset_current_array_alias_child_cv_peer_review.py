"""Count repeated array references without multiplying the child-table edge."""
import json

from string_offset_undefined_cv_review import HELPERS, guards, seek


def render(program, filename_b64):
    checks = [
        'S_initial = $php_run(' + program + ', 0, ' + json.dumps(filename_b64) + ')',
        'S_initial.COMPLETION = BUDGET',
    ] + seek('S_initial', 1, 'S') + [
        'S.TODO = (STRING_READ_RESULT pstringread) :: ptask_tail*',
        r'S.CURRENT = eps /\ S.FRAMES = eps',
        'pkeyread = pstringread.READ',
        r'pstringread.PHASE = STRING_CAST /\ pkeyread.PHASE = KEY_CV /\ pkeyread.VALUE = PNULL',
        r'pstringread.BASECELL = eps /\ pstringread.KEYCELL = eps',
        'pkeyread.NAME = $ptascii("missing")',
        'pkeyread.INPUT = VARIABLE pkeyread.NAME pkeyread.LINE',
        'pkeyread.BASE = PSTRING_CARRIER INTERNED_STRING ($ptascii("abcd"))',
        'pkeyread.OWNERS = BASE_VALUE (KNOWN pkeyread.BASE)',
        '$lookup(S.ENV, pkeyread.NAME) = (n_key)',
        'S.STORE[n_key] = DEFINED (PARRAY n_array)',
        'n_capture_cell? = (n_key)',
        '$string_read_capture(S, pkeyread.INPUT) = ((PARRAY n_array, n_capture_cell?))',
        '$string_read_cell(S, n_key)',
        '$(n_array < |S.ARRAYS|)',
        '(HARRAY n_array) <- S.ALLOCATIONS',
        'S.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (DIRECT (PINT 0)), ENTRY (KINT 1) (ALIAS n_payload), ENTRY (KINT 2) (ALIAS n_payload)]',
        'n_payload =/= n_key',
        '$call_reference_operand_valid(S, REFERENCE n_payload)',
        'S.STORE[n_payload] = DEFINED (PARRAY n_child)',
        'n_child =/= n_array',
        '$(n_child < |S.ARRAYS|)',
        '(HARRAY n_child) <- S.ALLOCATIONS',
        'S.ARRAYS[n_child].ITEMS = eps',
        'H = $heap_graph(S)',
        '(HARRAY n_array) <- $heap_prune(H).NODES',
        '(HCELL n_payload) <- $heap_prune(H).NODES',
        '(HARRAY n_child) <- $heap_prune(H).NODES',
        '$node_children(S, HCELL n_key) = [HARRAY n_array]',
        '$node_children(S, HARRAY n_array) = [HCELL n_payload, HCELL n_payload]',
        '$node_children(S, HCELL n_payload) = [HARRAY n_child]',
        '$node_children(S, HARRAY n_child) = eps',
        # The complete precode snapshot grounds these source-specific counts.
        'H.ROOTS = [HCELL n_key, HARRAY n_child]',
        '$heap_owners(H, HCELL n_payload) = 2',
        '$heap_owners(H, HARRAY n_child) = 2',
        '$cast_truth_int(S, PARRAY n_child) = 0',
        '$cast_truth_int(S, PARRAY n_array) = 1',
        '$string_read_array_child(S, PARRAY n_child)',
        '~$literal_reference_plain_cell(S, n_payload)',
        '~$string_read_array_string_cell(S, n_payload)',
        '$string_read_array_child_cell(S, n_payload)',
        '~$string_read_array_entries(S.ARRAYS[n_array].ITEMS)',
        '~$string_read_array_alias_entries(S, S.ARRAYS[n_array].ITEMS)',
        '$string_read_array_current_entries(S, S.ARRAYS[n_array].ITEMS)',
        '$string_read_cv_receipt(pkeyread)',
        '$string_read_source(S, pstringread)',
        '$string_read_cv_key(S, pkeyread) = (PARRAY n_array)',
        '$string_read_current_offset(S, pstringread, PARRAY n_array) = (1)',
        '$string_read_current_offset(S, pstringread, PARRAY n_child) = eps',
        '$string_read_ready(S, pstringread)',
        '$task_nodes(STRING_READ_RESULT pstringread) = eps',
        *guards('S'),
    ]
    derived_start = len(checks)
    checks += [
        # This singleton layout replaces exactly the two old S_alias refusals.
        'S_single = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload)]]',
        '$heap_owners($heap_graph(S_single), HCELL n_payload) = 1',
        '$heap_owners($heap_graph(S_single), HARRAY n_child) = 2',
        '$string_read_array_current_entries(S_single, S_single.ARRAYS[n_array].ITEMS)',
        '$string_read_cv_key(S_single, pkeyread) = (PARRAY n_array)',
        '$string_read_current_offset(S_single, pstringread, PARRAY n_array) = (1)',
        'S_three = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload), ENTRY (KINT 1) (ALIAS n_payload), ENTRY (KINT 2) (ALIAS n_payload)]]',
        '$heap_owners($heap_graph(S_three), HCELL n_payload) = 3',
        '$heap_owners($heap_graph(S_three), HARRAY n_child) = 2',
        '$string_read_array_child_cell(S_three, n_payload)',
        '$string_read_current_offset(S_three, pstringread, PARRAY n_array) = (1)',
        # A second real CELL adds one payload edge, unlike another same-cell alias.
        'n_other = |S.STORE|',
        'S_split = S[.STORE = S.STORE ++ [DEFINED (PARRAY n_child)]][.REFCELLS = n_other :: S.REFCELLS][.ALLOCATIONS = S.ALLOCATIONS ++ [HCELL n_other]][.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload), ENTRY (KINT 1) (ALIAS n_other)]]',
        '$node_children(S_split, HCELL n_other) = [HARRAY n_child]',
        '$heap_owners($heap_graph(S_split), HARRAY n_child) = 3',
        '$string_read_array_child_cell(S_split, n_payload)',
        '$string_read_array_child_cell(S_split, n_other)',
        '$string_read_current_offset(S_split, pstringread, PARRAY n_array) = (1)',
        # A live child or physical wrapper record alone cannot own a reference.
        '~$string_read_array_child_cell(S, |S.STORE|)',
        'S_unmarked = S[.REFCELLS = eps]',
        '$string_read_cv_key(S_unmarked, pkeyread) = eps',
        'S_missing = S[.ALLOCATIONS = $destruction_node_delete(S.ALLOCATIONS, HCELL n_payload)]',
        '$string_read_array_child(S_missing, PARRAY n_child)',
        '~$string_read_array_child_cell(S_missing, n_payload)',
        '$string_read_cv_key(S_missing, pkeyread) = eps',
        'S_undefined = S[.STORE[n_payload] = UNDEFINED]',
        '$string_read_cv_key(S_undefined, pkeyread) = eps',
        'S_orphan = S[.ENV = eps]',
        '$string_read_array_child(S_orphan, PARRAY n_child)',
        '~((HCELL n_payload) <- $heap_prune($heap_graph(S_orphan)).NODES)',
        '~$string_read_array_child_cell(S_orphan, n_payload)',
        '$string_read_cv_key(S_orphan, pkeyread) = (PNULL)',
        '$string_read_current_offset(S_orphan, pstringread, PARRAY n_array) = eps',
        'S_ghost = S[.STORE = S.STORE ++ [DEFINED (PARRAY n_child)]][.REFCELLS = n_other :: S.REFCELLS][.ALLOCATIONS = S.ALLOCATIONS ++ [HCELL n_other]]',
        '$call_reference_operand_valid(S_ghost, REFERENCE n_other)',
        '~$string_read_array_child_cell(S_ghost, n_other)',
        'S_child_missing = S[.ALLOCATIONS = $destruction_node_delete(S.ALLOCATIONS, HARRAY n_child)]',
        '$string_read_cv_key(S_child_missing, pkeyread) = eps',
        'S_child_oob = S[.STORE[n_payload] = DEFINED (PARRAY (|S.ARRAYS|))]',
        '$string_read_cv_key(S_child_oob, pkeyread) = eps',
        'S_cycle = S[.ARRAYS[n_child].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload)]]',
        '$string_read_cv_key(S_cycle, pkeyread) = eps',
        'S_object = S[.ARRAYS[n_child].ITEMS = [ENTRY (KINT 0) (DIRECT (POBJECT 0))]]',
        '$string_read_cv_key(S_object, pkeyread) = eps',
        # Both existing per-entry domains still compose with a quiet child cell.
        'S_primitive = S[.STORE[n_payload] = DEFINED (PBOOL false)]',
        '~$string_read_array_child_cell(S_primitive, n_payload)',
        '$string_read_current_offset(S_primitive, pstringread, PARRAY n_array) = (1)',
        'S_string = S[.STORE[n_payload] = DEFINED (PSTRING_CARRIER INTERNED_STRING ($ptascii("0")))]',
        '~$string_read_array_child_cell(S_string, n_payload)',
        '$string_read_current_offset(S_string, pstringread, PARRAY n_array) = (1)',
        'S_mix = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (DIRECT (PARRAY n_child)), ENTRY (KINT 1) (ALIAS n_payload), ENTRY (KINT 2) (DIRECT PNULL)]]',
        '$node_children(S_mix, HARRAY n_array) = [HARRAY n_child, HCELL n_payload]',
        '$heap_owners($heap_graph(S_mix), HARRAY n_child) = 3',
        '$string_read_current_offset(S_mix, pstringread, PARRAY n_array) = (1)',
        'S_scalar = S[.ARRAYS[n_child].ITEMS = [ENTRY (KINT 0) (DIRECT (PSTRING ([0]))), ENTRY (KINT 1) (DIRECT (PBOOL false))]]',
        '$string_read_array_child_cell(S_scalar, n_payload)',
        '$string_read_current_offset(S_scalar, pstringread, PARRAY n_array) = (1)',
        'S_empty = S[.ARRAYS[n_array].ITEMS = eps]',
        '$string_read_current_offset(S_empty, pstringread, PARRAY n_array) = (0)',
    ]
    for name, field, record in (
        ('typed', 'PROPREFS', '{CELL n_payload, SOURCES eps}'),
        ('coercion', 'REFCOERCIONS', '{CELL n_payload, SITE pkeyread.SITE, LINE pkeyread.LINE, VALUE eps}'),
        ('backing', 'PARAMETERBACKINGS', '{FUNCTION pkeyread.SITE, INDEX 0, CELL n_payload, LINE pkeyread.LINE, VALUE eps}'),
    ):
        state = 'S_' + name
        checks += [
            state + ' = S[.' + field + ' = ' + record + ' :: S.' + field + ']',
            '~$string_read_array_child_cell(' + state + ', n_payload)',
            '$string_read_cv_key(' + state + ', pkeyread) = eps',
        ]
    checks += [
        'S_marked_key = S[.REFCELLS = n_key :: S.REFCELLS]',
        '$string_read_cv_key(S_marked_key, pkeyread) = eps',
        '~$string_read_source(S[.ORIGIN = eps], pstringread)',
        '~$string_read_source(S, pstringread[.KEYCELL = (n_key)])',
        '$string_read_phase(pkeyread.BASE, PARRAY n_array) = eps',
        'pkeyread_initial = pkeyread[.PHASE = KEY_NULL][.VALUE = PARRAY n_array][.NAME = eps]',
        '$string_read_cv_key(S, pkeyread_initial) = eps',
        '$string_read_resume(S_cycle, pstringread) = S_cycle[.COMPLETION = UNSUPPORTED "string offset changed key locator after callback"]',
    ]
    derived_count = len(checks) - derived_start
    checks += [
        'PhpStep: S ~> S_byte',
        'S_byte = S[.TODO = ptask_tail*][.RESULT = KNOWN (PSTRING_CARRIER INTERNED_STRING ([98]))][.BASE = BASE_VALUE (KNOWN PNULL)]',
        '$heap_graph(S_byte) = H',
        '$drive_steps(S, 0) = S[.COMPLETION = BUDGET]',
        '$drive_steps(S, 1) = S_byte[.COMPLETION = BUDGET]',
        *guards('S_byte'),
    ]
    return (HELPERS + '\ndec $main() : bool\ndef $main() = true\n' + ''.join(
        '  -- ' + (check if check.startswith('PhpStep:') else 'if ' + check) + '\n'
        for check in checks), len(checks), derived_count)
