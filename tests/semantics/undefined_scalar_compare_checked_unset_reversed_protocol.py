"""Checked source-right removal preserves first NULL and folds the other quietly."""
import base64
import json

from undefined_spaceship_protocol import PREFIX as COMMON, text

PREFIX = COMMON.replace('BINARY_RIGHT SPACESHIP poperand z',
                        'BINARY_RIGHT pbin poperand z\n  -- if '
                        + r'pbin = GREATER \/ pbin = GREATEREQUAL')


def checks(program, path, name):
    reference = name == 'greater-equal-checked-reference-unset'
    op = 'GREATEREQUAL' if reference else 'GREATER'
    answer = 'true' if reference else 'false'
    original = 'BINARY_RIGHT ' + op + ' (VARIABLE ($ptascii("missing")) z_left) 10'
    frozen = 'BINARY_RIGHT ' + op + ' (KNOWN PNULL) 10'
    expected = ('H:1:1:10:1;R:1:1:1:1:1;A:1:1:1;END;' if reference else
                'H:1:1:10:1;R:1:1:1:1;END;')
    values = [
        'S_initial = $php_run(' + program + ',0,' + json.dumps(base64.b64encode(str(path).encode()).decode()) + ')',
        'S_initial.COMPLETION = BUDGET', 'S_found = $us_seek(S_initial,0,1200)',
        r'S_found.COMPLETION = NORMAL \/ S_found.COMPLETION = BUDGET',
        'S = S_found[.COMPLETION = NORMAL]', '$us_stage(S,0)', '$us_guard(S)',
        'S.TODO = ptask_original :: ptask_tail*', 'ptask_original = ' + original,
        'S.RESULT = VARIABLE ($ptascii("right")) z_right',
        '$error_read_plan(S) = (perrorread)', '$error_read_valid(S,perrorread)',
        '$error_read_shape(ptask_original,S.RESULT,S.BASE) = (perrorread)',
        'perrorread.NAME = $ptascii("missing")', 'perrorread.LINE = 10',
        'perrorread.TASK = ' + frozen, 'perrorread.RESULT = S.RESULT',
        '$scalar_compare_read_other(S,perrorread)',
        '~$scalar_compare_checked_right_missing(S,perrorread)',
        '$lookup(S.ENV,$ptascii("right")) = (n_right)',
        'S.STORE[n_right] = DEFINED pvalue_right',
        '$string_plain(pvalue_right) = PSTRING ($ptascii("0"))',
        '$lookup(S.ENV,$ptascii("missing")) = eps',
        '$heap_owners($heap_prune($heap_graph(S)),HCELL n_right) = ' + ('2' if reference else '1'),
        '$task_nodes(ERROR_READ_RESULT perrorread) = eps', 'S.BORROWEDREAD = eps',
        'S_warn_pause = $drive_steps(S,1)', 'S_warn_pause.COMPLETION = BUDGET',
        'S_warn = S_warn_pause[.COMPLETION = NORMAL]', '$us_stage(S_warn,1)',
        'S_warn = $prune_allocations($error_read_begin(S))',
        'S_warn.TODO = (ERROR_HANDLER_INVOKE perrorcall) :: ptask_tail*',
        'perrorcall.RESUME = ERROR_READ_RESULT perrorread',
        'perrorcall.MESSAGE = $ptascii("Undefined variable $missing")',
        'perrorcall.LINE = 10', 'perrorcall.LEVEL = 2',
        '$error_call_valid(S_warn,perrorcall)', 'S_warn.EVENTS = S.EVENTS', '$us_guard(S_warn)',
        'S_return_found = $us_seek(S_warn,2,1200)',
        r'S_return_found.COMPLETION = NORMAL \/ S_return_found.COMPLETION = BUDGET',
        'S_return = S_return_found[.COMPLETION = NORMAL]',
        'S_return.TODO = (ERROR_HANDLER_RESULT perrorcall_entered) :: ptask_tail*',
        'perrorcall_entered.RESUME = ERROR_READ_RESULT perrorread',
        '$call_task_valid(S_return,ERROR_HANDLER_RESULT perrorcall_entered)',
        'S_return.RESULT = KNOWN (PBOOL true)', '$us_guard(S_return)',
        'S_resume_found = $us_seek(S_return,3,1200)',
        r'S_resume_found.COMPLETION = NORMAL \/ S_resume_found.COMPLETION = BUDGET',
        'S_resume = S_resume_found[.COMPLETION = NORMAL]',
        'S_resume.TODO = (ERROR_READ_RESULT perrorread) :: ptask_tail*',
        '$error_read_valid(S_resume,perrorread)',
        '$lookup(S_resume.ENV,$ptascii("right")) = eps',
        '$lookup(S_resume.ENV,$ptascii("missing")) = (n_missing)',
        'S_resume.STORE[n_missing] = DEFINED (PINT 9)',
        '~$scalar_compare_read_other(S_resume,perrorread)',
        '~$scalar_compare_read_again(S_resume,perrorread)',
        '$scalar_compare_checked_right_missing(S_resume,perrorread)',
        '~$scalar_compare_checked_missing(S_resume,perrorread)',
        '~$spaceship_checked_missing(S_resume,perrorread)',
        'S_resume.EVENTS = S_return.EVENTS', 'S_resume.ERRORHANDLER = S.ERRORHANDLER',
        r'S_resume.CURRENT = eps /\ S_resume.FRAMES = eps', 'S_resume.BORROWEDREAD = eps',
        '$us_guard(S_resume)', 'PhpStep: S_resume ~> S_restored',
        'S_restored = S_resume[.TODO = perrorread.TASK :: ptask_tail*][.RESULT = KNOWN PNULL][.BASE = perrorread.BASE]',
        '$error_read_plan(S_restored) = eps', 'PhpStep: S_restored ~> S_compared',
        'S_compared = S_restored[.TODO = ptask_tail*][.RESULT = KNOWN (PBOOL ' + answer + ')][.BASE = BASE_VALUE (KNOWN PNULL)]',
        'S_compared.EVENTS = S_resume.EVENTS', '$us_guard(S_compared)',
        '$heap_owners($heap_prune($heap_graph(S_resume)),HCELL n_right) = ' + ('1' if reference else '0'),
        'S_done = $drive_steps(S_compared,4000)', 'S_done.COMPLETION = NORMAL',
        r'S_done.TODO = eps /\ S_done.CURRENT = eps /\ S_done.FRAMES = eps',
        '$us_output(S_done.EVENTS) = ' + text(expected), '$us_guard(S_done)',
        'S_done.CODE = S_initial.CODE', 'S_done.POOLS = S_initial.POOLS',
        'S_done = $drive_steps(S_initial[.COMPLETION = NORMAL],4000)',
        'S_zero = $drive_steps(S_resume,0)', 'S_zero = S_resume[.COMPLETION = BUDGET]',
        '$drive_steps(S_zero[.COMPLETION = NORMAL],4000) = S_done',
        '$drive_steps(S_warn_pause[.COMPLETION = NORMAL],4000) = S_done',
        '$scalar_compare_right_read_shape(ptask_original,S.RESULT,S.BASE) = (perrorread_right)',
        'perrorread_right =/= perrorread', '$error_read_valid(S_resume,perrorread_right)',
        '~$scalar_compare_checked_right_missing(S_resume,perrorread_right)',
        'S_unread = $unset_name(S_resume,$ptascii("missing"))[.TODO = (ERROR_READ_RESULT perrorread_right) :: ptask_tail*]',
        '$error_read_valid(S_unread,perrorread_right)',
        '~$scalar_compare_checked_right_missing(S_unread,perrorread_right)',
        '$scalar_compare_read_again(S_unread,perrorread_right)',
        'PhpStep: S_unread ~> S_unread_restored',
        'S_unread_restored = S_unread[.TODO = perrorread_right.TASK :: ptask_tail*][.RESULT = KNOWN PNULL][.BASE = perrorread_right.BASE]',
        '$error_read_plan(S_unread_restored) = (perrorread_later)',
        'perrorread_later.INPUT = KNOWN PNULL', 'perrorread_later.NAME = $ptascii("missing")',
        '$error_read_valid(S_unread_restored,perrorread_later)',
        'S_later_pause = $drive_steps(S_unread_restored,1)', 'S_later_pause.COMPLETION = BUDGET',
        'S_later = S_later_pause[.COMPLETION = NORMAL]', '$us_stage(S_later,1)',
        'S_later.TODO = (ERROR_HANDLER_INVOKE perrorcall_later) :: ptask_tail*',
        'perrorcall_later.RESUME = ERROR_READ_RESULT perrorread_later',
        'S_later.EVENTS = S_unread.EVENTS',
        'S_undefined = S[.TODO = (ERROR_READ_RESULT perrorread) :: ptask_tail*][.STORE = $set_cell(S.STORE,n_right,UNDEFINED)]',
        '$error_read_valid(S_undefined,perrorread)', '$scalar_compare_checked_right_missing(S_undefined,perrorread)',
        'PhpStep: S_undefined ~> S_undefined_restored',
        'S_undefined_restored = S_undefined[.TODO = perrorread.TASK :: ptask_tail*][.RESULT = KNOWN PNULL][.BASE = perrorread.BASE]',
        'S_undefined_restored.EVENTS = S_undefined.EVENTS', '$error_read_plan(S_undefined_restored) = eps',
        'S_both = S_undefined[.TODO = ptask_original :: ptask_tail*][.RESULT = perrorread.INPUT]',
        '$error_read_plan(S_both) = (perrorread_right)',
        '$scalar_compare_missing_pair(S_both,perrorread_right)',
        '~$scalar_compare_missing_pair(S_both,perrorread)',
        '$scalar_compare_checked_right_missing(S_both,perrorread)',
        'perrorread_bad = perrorread[.ORIGINAL = BINARY_RIGHT ' + op + ' (VARIABLE ($ptascii("missing")) z_left) 999][.TASK = BINARY_RIGHT ' + op + ' (KNOWN PNULL) 999][.LINE = 999]',
        '$error_read_shape(perrorread_bad.ORIGINAL,perrorread_bad.INPUT,perrorread_bad.BASE) = (perrorread_bad)',
        '$scalar_compare_checked_right_missing(S_resume,perrorread_bad)',
        '~$error_read_source(S_resume,perrorread_bad)', '~$error_read_valid(S_resume,perrorread_bad)',
        '~$error_call_valid(S_warn,perrorcall[.RESUME = ERROR_READ_RESULT perrorread_bad])',
        'perrorread_bad_left = perrorread[.ORIGINAL = BINARY_RIGHT ' + op + ' (VARIABLE ($ptascii("missing")) 999) 10]',
        '$error_read_shape(perrorread_bad_left.ORIGINAL,perrorread_bad_left.INPUT,perrorread_bad_left.BASE) = (perrorread_bad_left)',
        '$scalar_compare_checked_right_missing(S_resume,perrorread_bad_left)',
        '~$error_read_source(S_resume,perrorread_bad_left)', '~$error_read_valid(S_resume,perrorread_bad_left)',
        '~$error_read_valid(S_resume[.ORIGIN = eps],perrorread)',
        '~$error_read_valid(S_resume[.CODE = eps],perrorread)',
        '~$error_call_valid(S_warn,perrorcall[.LEVEL = 8])',
        '~$error_call_valid(S_warn,perrorcall[.MESSAGE = eps])',
        'perrorread_forward = perrorread[.ORIGINAL = BINARY_RIGHT EQUAL (VARIABLE ($ptascii("missing")) z_left) 10][.TASK = BINARY_RIGHT EQUAL (KNOWN PNULL) 10]',
        '$error_read_shape(perrorread_forward.ORIGINAL,perrorread_forward.INPUT,perrorread_forward.BASE) = (perrorread_forward)',
        '~$scalar_compare_checked_right_missing(S_resume,perrorread_forward)',
        '$scalar_compare_read_again(S_resume,perrorread_forward)', '~$error_read_valid(S_resume,perrorread_forward)',
        'perrorread_space = perrorread[.ORIGINAL = BINARY_RIGHT SPACESHIP (VARIABLE ($ptascii("missing")) z_left) 10][.TASK = BINARY_RIGHT SPACESHIP (KNOWN PNULL) 10]',
        '$spaceship_read_again(S_resume,perrorread_space)',
        '~$scalar_compare_checked_right_missing(S_resume,perrorread_space)', '~$error_read_valid(S_resume,perrorread_space)',
    ]
    if reference:
        values += [
            '$lookup(S.ENV,$ptascii("alias")) = (n_right)', 'n_right <- S.REFCELLS',
            '$lookup(S_resume.ENV,$ptascii("alias")) = (n_right)',
            'S_resume.STORE[n_right] = DEFINED pvalue_alias',
            '$string_plain(pvalue_alias) = PSTRING ($ptascii("0"))', 'n_right <- S_resume.REFCELLS',
            '$lookup(S_done.ENV,$ptascii("alias")) = (n_right)',
            'S_done.STORE[n_right] = DEFINED (PINT 5)',
            '$heap_owners($heap_prune($heap_graph(S_done)),HCELL n_right) = 1',
        ]
    else:
        values.append('~(n_right <- S.REFCELLS)')
    return values + ['$lookup(S_done.ENV,$ptascii("right")) = eps']
