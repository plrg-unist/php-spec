"""Authenticate a live REQUEST-string reference without converting its bytes."""
import json

from string_offset_undefined_cv_review import HELPERS, guards, seek


def render(program, filename_b64):
    checks = [
        'S_initial = $php_run(' + program + ', 0, ' + json.dumps(filename_b64) + ')',
        'S_initial.COMPLETION = BUDGET',
    ] + seek('S_initial', 1, 'S') + [
        'S.TODO = (STRING_READ_RESULT pstringread) :: ptask_tail*',
        r'S.CURRENT = eps /\ S.FRAMES = eps',
        'pkeyread = pstringread.READ',
        r'pstringread.PHASE = STRING_CAST /\ pkeyread.PHASE = KEY_CV /\ pkeyread.VALUE = PNULL',
        r'pstringread.BASECELL = eps /\ pstringread.KEYCELL = eps',
        'pkeyread.BASE = PSTRING_CARRIER INTERNED_STRING ($ptascii("abcd"))',
        '$lookup(S.ENV, pkeyread.NAME) = (n_key)',
        'S.STORE[n_key] = DEFINED (PARRAY n_array)',
        'n_capture_cell? = (n_key)',
        '$string_read_capture(S, pkeyread.INPUT) = ((PARRAY n_array, n_capture_cell?))',
        '$string_read_cell(S, n_key)',
        '$(n_array < |S.ARRAYS|)',
        '(HARRAY n_array) <- S.ALLOCATIONS',
        'H = $heap_graph(S)',
        '(HARRAY n_array) <- $heap_prune(H).NODES',
        'S.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (DIRECT (PINT 0)), ENTRY (KINT 1) (ALIAS n_payload), ENTRY (KINT 2) (ALIAS n_payload)]',
        'pvalue_payload = PSTRING_CARRIER (REQUEST_STRING n_identity) n_bytes*',
        'S.STORE[n_payload] = DEFINED pvalue_payload',
        'n_bytes* = $ptascii("2tail")',
        '$(n_identity < |S.STRINGDATA|)',
        'S.STRINGDATA[n_identity] = n_bytes*',
        '$string_carrier_valid(S, pvalue_payload)',
        '$c_string(n_bytes*) = n_bytes*',
        '$call_reference_operand_valid(S, REFERENCE n_payload)',
        '(HCELL n_payload) <- $heap_prune(H).NODES',
        '$node_children(S, HCELL n_key) = [HARRAY n_array]',
        '$node_children(S, HARRAY n_array) = [HCELL n_payload, HCELL n_payload]',
        '$node_children(S, HCELL n_payload) = eps',
        '~$literal_reference_plain_cell(S, n_payload)',
        '~$string_read_array_entries(S.ARRAYS[n_array].ITEMS)',
        '~$string_read_array_alias_entries(S, S.ARRAYS[n_array].ITEMS)',
        '$string_read_array_string_cell(S, n_payload)',
        '$string_read_array_current_entries(S, S.ARRAYS[n_array].ITEMS)',
        '$string_read_source(S, pstringread)',
        '$string_read_cv_key(S, pkeyread) = (PARRAY n_array)',
        '$string_read_current_offset(S, pstringread, PARRAY n_array) = (1)',
        '$string_read_ready(S, pstringread)',
        '$task_nodes(STRING_READ_RESULT pstringread) = eps',
        *guards('S'),
    ]
    derived_start = len(checks)
    checks += [
        # Registry authentication and real reference-cell ownership are separate.
        'S_registry = S[.STRINGDATA[n_identity] = $ptascii("3tail")]',
        '~$string_carrier_valid(S_registry, pvalue_payload)',
        '~$string_read_array_string_cell(S_registry, n_payload)',
        '$string_read_cv_key(S_registry, pkeyread) = eps',
        '$string_read_resume(S_registry, pstringread) = S_registry[.COMPLETION = UNSUPPORTED "string offset changed key locator after callback"]',
        'S_bad_id = S[.STORE[n_payload] = DEFINED (PSTRING_CARRIER (REQUEST_STRING (|S.STRINGDATA|)) n_bytes*)]',
        '$string_read_cv_key(S_bad_id, pkeyread) = eps',
        'S_bad_bytes = S[.STORE[n_payload] = DEFINED (PSTRING_CARRIER (REQUEST_STRING n_identity) ($ptascii("other")))]',
        '$string_read_cv_key(S_bad_bytes, pkeyread) = eps',
        'S_nul = S[.STRINGDATA[n_identity] = [50, 0]][.STORE[n_payload] = DEFINED (PSTRING_CARRIER (REQUEST_STRING n_identity) ([50, 0]))]',
        '$string_carrier_valid(S_nul, PSTRING_CARRIER (REQUEST_STRING n_identity) ([50, 0]))',
        '~$string_read_array_string_cell(S_nul, n_payload)',
        '$string_read_cv_key(S_nul, pkeyread) = eps',
        'S_missing = S[.ALLOCATIONS = $destruction_node_delete(S.ALLOCATIONS, HCELL n_payload)]',
        '$string_carrier_valid(S_missing, pvalue_payload)',
        '~$string_read_array_string_cell(S_missing, n_payload)',
        'n_ghost = |S.STORE|',
        'S_ghost = S[.STORE = S.STORE ++ [DEFINED pvalue_payload]][.REFCELLS = n_ghost :: S.REFCELLS][.ALLOCATIONS = S.ALLOCATIONS ++ [HCELL n_ghost]]',
        '$call_reference_operand_valid(S_ghost, REFERENCE n_ghost)',
        '$string_carrier_valid(S_ghost, pvalue_payload)',
        '~((HCELL n_ghost) <- $heap_prune($heap_graph(S_ghost)).NODES)',
        '~$string_read_array_string_cell(S_ghost, n_ghost)',
        'S_elsewhere = S[.ENV = [BIND ($ptascii("keeper")) n_key]]',
        '$string_read_array_string_cell(S_elsewhere, n_payload)',
        '$string_read_cv_key(S_elsewhere, pkeyread) = (PNULL)',
        '$string_read_current_offset(S_elsewhere, pstringread, PARRAY n_array) = eps',
        'S_unmarked = S[.REFCELLS = eps]',
        '$string_read_cv_key(S_unmarked, pkeyread) = eps',
        'S_undefined = S[.STORE[n_payload] = UNDEFINED]',
        '$string_read_cv_key(S_undefined, pkeyread) = eps',
        'S_typed = S[.PROPREFS = {CELL n_payload, SOURCES eps} :: S.PROPREFS]',
        '$string_read_cv_key(S_typed, pkeyread) = eps',
        'S_coercion = S[.REFCOERCIONS = {CELL n_payload, SITE pkeyread.SITE, LINE pkeyread.LINE, VALUE eps} :: S.REFCOERCIONS]',
        '$string_read_cv_key(S_coercion, pkeyread) = eps',
        'S_backing = S[.PARAMETERBACKINGS = {FUNCTION pkeyread.SITE, INDEX 0, CELL n_payload, LINE pkeyread.LINE, VALUE eps} :: S.PARAMETERBACKINGS]',
        '$string_read_cv_key(S_backing, pkeyread) = eps',
        'S_raw = S[.STORE[n_payload] = DEFINED (PSTRING n_bytes*)]',
        '$string_read_cv_key(S_raw, pkeyread) = eps',
        # Reconstruct precisely the four superseded string-payload assertions.
        'S_legacy_one = S[.STORE[n_payload] = DEFINED (PSTRING_CARRIER INTERNED_STRING ($ptascii("safe")))][.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload)]]',
        '~$literal_reference_plain_cell(S_legacy_one, n_payload)',
        '~$string_read_array_alias_entries(S_legacy_one, S_legacy_one.ARRAYS[n_array].ITEMS)',
        '$string_read_cv_key(S_legacy_one, pkeyread) = (PARRAY n_array)',
        'S_legacy_two = S[.STORE[n_payload] = DEFINED (PSTRING_CARRIER INTERNED_STRING ($ptascii("0")))][.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload), ENTRY (KINT 1) (ALIAS n_payload)]]',
        '$string_read_cv_key(S_legacy_two, pkeyread) = (PARRAY n_array)',
        'S_legacy_mixed = S_legacy_two[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (DIRECT (PINT 0)), ENTRY (KINT 1) (ALIAS n_payload)]]',
        '$string_read_cv_key(S_legacy_mixed, pkeyread) = (PARRAY n_array)',
        'S_legacy_three = S_legacy_two[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload), ENTRY (KINT 1) (DIRECT (PBOOL false)), ENTRY (KINT 2) (ALIAS n_payload)]]',
        '$string_read_cv_key(S_legacy_three, pkeyread) = (PARRAY n_array)',
        '~$string_read_array_string_cell(S, |S.STORE|)',
        'pkeyread_initial = pkeyread[.PHASE = KEY_NULL][.VALUE = PARRAY n_array][.NAME = eps]',
        '$string_read_cv_key(S, pkeyread_initial) = eps',
    ]
    derived_count = len(checks) - derived_start
    checks += [
        'PhpStep: S ~> S_byte',
        'S_byte = S[.TODO = ptask_tail*][.RESULT = KNOWN (PSTRING_CARRIER INTERNED_STRING ([98]))][.BASE = BASE_VALUE (KNOWN PNULL)]',
        '$heap_graph(S_byte) = H',
        '$drive_steps(S, 0) = S[.COMPLETION = BUDGET]',
        '$drive_steps(S, 1) = S_byte[.COMPLETION = BUDGET]',
        *guards('S_byte'),
    ]
    return (HELPERS + '\ndec $main() : bool\ndef $main() = true\n' + ''.join(
        '  -- ' + (check if check.startswith('PhpStep:') else 'if ' + check) + '\n'
        for check in checks), len(checks), derived_count)
