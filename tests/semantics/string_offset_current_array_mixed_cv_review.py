"""Compose DIRECT and plain ALIAS admission at a genuine current-CV frontier."""
import json

from string_offset_undefined_cv_review import HELPERS, guards, seek


def render(program, filename_b64):
    checks = [
        'S_initial = $php_run(' + program + ', 0, ' + json.dumps(filename_b64) + ')',
        'S_initial.COMPLETION = BUDGET',
    ] + seek('S_initial', 1, 'S') + [
        'S.TODO = (STRING_READ_RESULT pstringread) :: ptask_tail*',
        r'S.CURRENT = eps /\ S.FRAMES = eps',
        r'pstringread.PHASE = STRING_CAST /\ pstringread.READ.PHASE = KEY_CV /\ pstringread.READ.VALUE = PNULL',
        r'pstringread.BASECELL = eps /\ pstringread.KEYCELL = eps',
        '$lookup(S.ENV, pstringread.READ.NAME) = (n_key)',
        'S.STORE[n_key] = DEFINED (PARRAY n_array)',
        'n_capture_cell? = (n_key)',
        '$string_read_capture(S, pstringread.READ.INPUT) = ((PARRAY n_array, n_capture_cell?))',
        '~(n_key <- S.REFCELLS)',
        '$(n_array < |S.ARRAYS|)',
        '(HARRAY n_array) <- S.ALLOCATIONS',
        'H = $heap_graph(S)',
        '(HARRAY n_array) <- $heap_prune(H).NODES',
        'S.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (DIRECT (PINT 0)), ENTRY (KINT 1) (ALIAS n_payload)]',
        '$(n_payload < |S.STORE|)',
        'S.STORE[n_payload] = DEFINED (PBOOL false)',
        'n_payload <- S.REFCELLS',
        '(HCELL n_payload) <- S.ALLOCATIONS',
        '(HCELL n_payload) <- $heap_prune(H).NODES',
        '$literal_reference_plain_cell(S, n_payload)',
        '$node_children(S, HCELL n_key) = [HARRAY n_array]',
        '$node_children(S, HARRAY n_array) = [HCELL n_payload]',
        '$node_children(S, HCELL n_payload) = eps',
        '$string_read_cv_receipt(pstringread.READ)',
        '$string_read_source(S, pstringread)',
        '~$string_read_array_entries(S.ARRAYS[n_array].ITEMS)',
        '~$string_read_array_alias_entries(S, S.ARRAYS[n_array].ITEMS)',
        '$string_read_array_current_entries(S, S.ARRAYS[n_array].ITEMS)',
        '$string_read_cv_key(S, pstringread.READ) = (PARRAY n_array)',
        '$string_read_key_current(S, pstringread) = (PARRAY n_array)',
        '$string_read_current_offset(S, pstringread, PARRAY n_array) = (1)',
        '$string_read_offset(PARRAY n_array) = eps',
        '$string_read_ready(S, pstringread)',
        '$task_nodes(STRING_READ_RESULT pstringread) = eps',
        *guards('S'),
    ]
    derived_start = len(checks)
    checks += [
        '$string_read_array_current_entries(S, eps)',
        'S_empty = S[.ARRAYS[n_array].ITEMS = eps]',
        '$string_read_current_offset(S_empty, pstringread, PARRAY n_array) = (0)',
        'S_direct = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (DIRECT (PINT 0))]]',
        '$string_read_current_offset(S_direct, pstringread, PARRAY n_array) = (1)',
        'S_alias = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload)]]',
        '$string_read_current_offset(S_alias, pstringread, PARRAY n_array) = (1)',
        # These two mixed cases replace only the older derived refusal assertions.
        'S_alias_direct = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload), ENTRY (KINT 1) (DIRECT PNULL)]]',
        '$string_read_cv_key(S_alias_direct, pstringread.READ) = (PARRAY n_array)',
        'S_direct_alias = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (DIRECT PNULL), ENTRY (KINT 1) (ALIAS n_payload)]]',
        '$string_read_cv_key(S_direct_alias, pstringread.READ) = (PARRAY n_array)',
        'S_twice = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload), ENTRY (KINT 1) (DIRECT (PBOOL false)), ENTRY (KINT 2) (ALIAS n_payload)]]',
        '$node_children(S_twice, HARRAY n_array) = [HCELL n_payload, HCELL n_payload]',
        '$string_read_current_offset(S_twice, pstringread, PARRAY n_array) = (1)',
        # DIRECT keeps its older scalar domain, including uninterpreted strings.
        '$string_read_array_current_entries(S, [ENTRY (KINT 0) (DIRECT (PSTRING ([0]))), ENTRY (KINT 1) (ALIAS n_payload)])',
        '~$string_read_array_current_entries(S, [ENTRY (KINT 0) (DIRECT PUNDEFINED), ENTRY (KINT 1) (ALIAS n_payload)])',
        '~$string_read_array_current_entries(S, [ENTRY (KINT 0) (ALIAS n_payload), ENTRY (KINT 1) (DIRECT (PARRAY n_array))])',
        '~$string_read_array_current_entries(S, [ENTRY (KINT 0) (DIRECT (PINT 0)), ENTRY (KINT 1) UNINITIALIZED])',
        '~$string_read_array_current_entries(S, [ENTRY (KINT 0) (ALIAS n_payload), ENTRY (KINT 1) (INDIRECT n_key eps)])',
        'S_bad_tail = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (DIRECT (PINT 0)), ENTRY (KINT 1) (ALIAS (|S.STORE|))]]',
        '$string_read_cv_key(S_bad_tail, pstringread.READ) = eps',
        '$string_read_resume(S_bad_tail, pstringread) = S_bad_tail[.COMPLETION = UNSUPPORTED "string offset changed key locator after callback"]',
        'S_dead = S[.ENV = eps]',
        '$literal_reference_plain_cell(S_dead, n_payload)',
        '~((HCELL n_payload) <- $heap_prune($heap_graph(S_dead)).NODES)',
        '~$string_read_array_current_entries(S_dead, S_dead.ARRAYS[n_array].ITEMS)',
        '$string_read_current_offset(S_dead, pstringread, PARRAY n_array) = eps',
        'S_missing = S[.ALLOCATIONS = $destruction_node_delete(S.ALLOCATIONS, HCELL n_payload)]',
        '$string_read_cv_key(S_missing, pstringread.READ) = eps',
        'S_unmarked = S[.REFCELLS = eps]',
        '$string_read_cv_key(S_unmarked, pstringread.READ) = eps',
        'S_undefined = S[.STORE[n_payload] = UNDEFINED]',
        '$string_read_cv_key(S_undefined, pstringread.READ) = eps',
        'S_string = S[.STORE[n_payload] = DEFINED (PSTRING_CARRIER INTERNED_STRING ($ptascii("0")))]',
        '$string_read_cv_key(S_string, pstringread.READ) = (PARRAY n_array)',
        'S_nested = S[.STORE[n_payload] = DEFINED (PARRAY n_array)]',
        '$string_read_cv_key(S_nested, pstringread.READ) = eps',
        'S_object = S[.STORE[n_payload] = DEFINED (POBJECT 0)]',
        '$string_read_cv_key(S_object, pstringread.READ) = eps',
        'S_typed = S[.PROPREFS = {CELL n_payload, SOURCES eps} :: S.PROPREFS]',
        '$string_read_cv_key(S_typed, pstringread.READ) = eps',
        'S_coercion = S[.REFCOERCIONS = {CELL n_payload, SITE pstringread.READ.SITE, LINE pstringread.READ.LINE, VALUE eps} :: S.REFCOERCIONS]',
        '$string_read_cv_key(S_coercion, pstringread.READ) = eps',
        'S_backing = S[.PARAMETERBACKINGS = {FUNCTION pstringread.READ.SITE, INDEX 0, CELL n_payload, LINE pstringread.READ.LINE, VALUE eps} :: S.PARAMETERBACKINGS]',
        '$string_read_cv_key(S_backing, pstringread.READ) = eps',
        'S_null = S[.STORE[n_payload] = DEFINED PNULL]',
        '$string_read_current_offset(S_null, pstringread, PARRAY n_array) = (1)',
        'S_nan = S[.STORE[n_payload] = DEFINED (PFLOAT 9221120237041090560)]',
        '$string_read_current_offset(S_nan, pstringread, PARRAY n_array) = (1)',
        'S_marked = S[.REFCELLS = n_key :: S.REFCELLS]',
        '$string_read_cv_key(S_marked, pstringread.READ) = eps',
        'S_no_array = S[.ALLOCATIONS = $destruction_node_delete(S.ALLOCATIONS, HARRAY n_array)]',
        '$string_read_cv_key(S_no_array, pstringread.READ) = eps',
        'S_elsewhere = S[.ENV = [BIND ($ptascii("keeper")) n_key]]',
        '(HARRAY n_array) <- $heap_prune($heap_graph(S_elsewhere)).NODES',
        '$string_read_current_offset(S_elsewhere, pstringread, PARRAY n_array) = eps',
        'pkeyread_initial = pstringread.READ[.PHASE = KEY_NULL][.VALUE = PARRAY n_array][.NAME = eps]',
        '$string_read_current_offset(S, pstringread[.READ = pkeyread_initial], PARRAY n_array) = eps',
        '$string_read_phase(pstringread.READ.BASE, PARRAY n_array) = eps',
        '~$string_read_source(S, pstringread[.KEYCELL = (n_key)])',
        '~$string_read_source(S[.ORIGIN = eps], pstringread)',
    ]
    derived_count = len(checks) - derived_start
    checks += [
        'PhpStep: S ~> S_byte',
        'S_byte = S[.TODO = ptask_tail*][.RESULT = KNOWN (PSTRING_CARRIER INTERNED_STRING ([98]))][.BASE = BASE_VALUE (KNOWN PNULL)]',
        '$drive_steps(S, 0) = S[.COMPLETION = BUDGET]',
        '$drive_steps(S, 1) = S_byte[.COMPLETION = BUDGET]',
        *guards('S_byte'),
    ]
    return (HELPERS + '\ndec $main() : bool\ndef $main() = true\n' + ''.join(
        '  -- ' + (check if check.startswith('PhpStep:') else 'if ' + check) + '\n'
        for check in checks), len(checks), derived_count)
