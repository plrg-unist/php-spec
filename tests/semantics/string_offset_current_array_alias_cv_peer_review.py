"""Review repeated false aliases without reading their payload as the offset."""
import json

from string_offset_undefined_cv_review import HELPERS, guards, seek


def render(program, filename_b64):
    checks = [
        'S_initial = $php_run(' + program + ', 0, ' + json.dumps(filename_b64) + ')',
        'S_initial.COMPLETION = BUDGET',
    ] + seek('S_initial', 1, 'S') + [
        'S.TODO = (STRING_READ_RESULT pstringread) :: ptask_tail*',
        r'S.CURRENT = eps /\ S.FRAMES = eps',
        'pkeyread = pstringread.READ',
        r'pstringread.PHASE = STRING_CAST /\ pkeyread.PHASE = KEY_CV /\ pkeyread.VALUE = PNULL',
        r'pkeyread.NAME = $ptascii("missing") /\ pkeyread.KEY = KSTRING eps',
        'pkeyread.INPUT = VARIABLE pkeyread.NAME pkeyread.LINE',
        'pkeyread.BASE = PSTRING_CARRIER INTERNED_STRING ($ptascii("abc"))',
        'pkeyread.OWNERS = BASE_VALUE (KNOWN pkeyread.BASE)',
        r'pstringread.BASECELL = eps /\ pstringread.KEYCELL = eps',
        '$lookup(S.ENV, pkeyread.NAME) = (n_key)',
        'S.STORE[n_key] = DEFINED (PARRAY n_array)',
        'n_capture_cell? = (n_key)',
        '$string_read_capture(S, pkeyread.INPUT) = ((PARRAY n_array, n_capture_cell?))',
        '$string_read_cell(S, n_key)',
        '~(n_key <- S.REFCELLS)',
        '$(n_array < |S.ARRAYS|)',
        '(HARRAY n_array) <- S.ALLOCATIONS',
        'H = $heap_graph(S)',
        '(HARRAY n_array) <- $heap_prune(H).NODES',
        'S.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload), ENTRY (KINT 1) (ALIAS n_payload)]',
        '$(n_payload < |S.STORE|)',
        'S.STORE[n_payload] = DEFINED (PBOOL false)',
        'n_payload <- S.REFCELLS',
        '(HCELL n_payload) <- S.ALLOCATIONS',
        '(HCELL n_payload) <- $heap_prune(H).NODES',
        '$literal_reference_plain_cell(S, n_payload)',
        '$node_children(S, HCELL n_key) = [HARRAY n_array]',
        '$node_children(S, HARRAY n_array) = [HCELL n_payload, HCELL n_payload]',
        '$node_children(S, HCELL n_payload) = eps',
        '$heap_owners(H, HCELL n_payload) = 2',
        '$cast_truth_int(S, PBOOL false) = 0',
        '$string_read_cv_receipt(pkeyread)',
        '$string_read_source(S, pstringread)',
        '~$string_read_array_entries(S.ARRAYS[n_array].ITEMS)',
        '$string_read_array_alias_entries(S, S.ARRAYS[n_array].ITEMS)',
        '$string_read_cv_key(S, pkeyread) = (PARRAY n_array)',
        '$string_read_key_current(S, pstringread) = (PARRAY n_array)',
        '$string_read_current_offset(S, pstringread, PARRAY n_array) = (1)',
        '$string_read_offset(PARRAY n_array) = eps',
        '$string_read_ready(S, pstringread)',
        '$task_nodes(STRING_READ_RESULT pstringread) = eps',
        *guards('S'),
    ]
    derived_start = len(checks)
    checks += [
        # A live outside table and equal arena metadata cannot select the CV.
        'S_elsewhere = S[.ENV = [BIND ($ptascii("keeper")) n_key]]',
        '(HARRAY n_array) <- $heap_prune($heap_graph(S_elsewhere)).NODES',
        '$string_read_array_alias_entries(S_elsewhere, S_elsewhere.ARRAYS[n_array].ITEMS)',
        '$string_read_cv_key(S_elsewhere, pkeyread) = (PNULL)',
        '$string_read_current_offset(S_elsewhere, pstringread, PARRAY n_array) = eps',
        'n_other = |S.ARRAYS|',
        'S_metadata = S[.ARRAYS = S.ARRAYS ++ [S.ARRAYS[n_array]]]',
        '$string_read_current_offset(S_metadata, pstringread, PARRAY n_other) = eps',
        'S_unallocated = S_metadata[.STORE[n_key] = DEFINED (PARRAY n_other)]',
        '$string_read_cv_key(S_unallocated, pkeyread) = eps',
        'S_selected = S_unallocated[.ALLOCATIONS = S_unallocated.ALLOCATIONS ++ [HARRAY n_other]]',
        '$string_read_cv_key(S_selected, pkeyread) = (PARRAY n_other)',
        '$string_read_current_offset(S_selected, pstringread, PARRAY n_other) = (1)',
        '$string_read_current_offset(S_selected, pstringread, PARRAY n_array) = eps',
        'S_array_missing = S[.ALLOCATIONS = $destruction_node_delete(S.ALLOCATIONS, HARRAY n_array)]',
        '$string_read_cv_key(S_array_missing, pkeyread) = eps',
        'S_marked = S[.REFCELLS = n_key :: S.REFCELLS]',
        '$string_read_cv_key(S_marked, pkeyread) = eps',
        # Physical marked metadata alone is insufficient for an ALIAS entry.
        'S_dead = S[.ENV = eps]',
        '$literal_reference_plain_cell(S_dead, n_payload)',
        '~((HCELL n_payload) <- $heap_prune($heap_graph(S_dead)).NODES)',
        '~$string_read_array_alias_entries(S_dead, S_dead.ARRAYS[n_array].ITEMS)',
        'S_cell_missing = S[.ALLOCATIONS = $destruction_node_delete(S.ALLOCATIONS, HCELL n_payload)]',
        '$string_read_cv_key(S_cell_missing, pkeyread) = eps',
        'S_unmarked = S[.REFCELLS = eps]',
        '$string_read_cv_key(S_unmarked, pkeyread) = eps',
        'S_undefined = S[.STORE[n_payload] = UNDEFINED]',
        '$string_read_cv_key(S_undefined, pkeyread) = eps',
        'S_tail = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (ALIAS n_payload), ENTRY (KINT 1) (ALIAS (|S.STORE|))]]',
        '$string_read_cv_key(S_tail, pkeyread) = eps',
        '$string_read_resume(S_tail, pstringread) = S_tail[.COMPLETION = UNSUPPORTED "string offset changed key locator after callback"]',
        '~$string_read_array_alias_entries(S, eps)',
        'S_mixed = S[.ARRAYS[n_array].ITEMS = [ENTRY (KINT 0) (DIRECT PNULL), ENTRY (KINT 1) (ALIAS n_payload)]]',
        '$string_read_cv_key(S_mixed, pkeyread) = eps',
        'S_typed = S[.PROPREFS = {CELL n_payload, SOURCES eps} :: S.PROPREFS]',
        '$string_read_cv_key(S_typed, pkeyread) = eps',
        'S_coercion = S[.REFCOERCIONS = {CELL n_payload, SITE pkeyread.SITE, LINE pkeyread.LINE, VALUE eps} :: S.REFCOERCIONS]',
        '$string_read_cv_key(S_coercion, pkeyread) = eps',
        'S_backing = S[.PARAMETERBACKINGS = {FUNCTION pkeyread.SITE, INDEX 0, CELL n_payload, LINE pkeyread.LINE, VALUE eps} :: S.PARAMETERBACKINGS]',
        '$string_read_cv_key(S_backing, pkeyread) = eps',
        'S_string = S[.STORE[n_payload] = DEFINED (PSTRING_CARRIER INTERNED_STRING ($ptascii("0")))]',
        '$string_read_cv_key(S_string, pkeyread) = eps',
        'S_nested = S[.STORE[n_payload] = DEFINED (PARRAY n_array)]',
        '$string_read_cv_key(S_nested, pkeyread) = eps',
        'S_object = S[.STORE[n_payload] = DEFINED (POBJECT 0)]',
        '$string_read_cv_key(S_object, pkeyread) = eps',
        'S_int = S[.STORE[n_payload] = DEFINED (PINT (-9223372036854775808))]',
        '$string_read_current_offset(S_int, pstringread, PARRAY n_array) = (1)',
        'S_bad_int = S[.STORE[n_payload] = DEFINED (PINT 9223372036854775808)]',
        '$string_read_cv_key(S_bad_int, pkeyread) = eps',
        'S_bad_float = S[.STORE[n_payload] = DEFINED (PFLOAT 18446744073709551616)]',
        '$string_read_cv_key(S_bad_float, pkeyread) = eps',
        # Initial ARRAY keys never receive the initially undefined CV receipt.
        '$string_read_phase(pkeyread.BASE, PARRAY n_array) = eps',
        'pkeyread_initial = pkeyread[.PHASE = KEY_NULL][.VALUE = PARRAY n_array][.NAME = eps]',
        '$string_read_cv_key(S, pkeyread_initial) = eps',
        '$string_read_current_offset(S, pstringread[.READ = pkeyread_initial], PARRAY n_array) = eps',
        '~$string_read_source(S[.ORIGIN = eps], pstringread)',
        '~$string_read_source(S, pstringread[.KEYCELL = (n_key)])',
    ]
    derived_count = len(checks) - derived_start
    checks += [
        'PhpStep: S ~> S_byte',
        'S_byte = S[.TODO = ptask_tail*][.RESULT = KNOWN (PSTRING_CARRIER INTERNED_STRING ([98]))][.BASE = BASE_VALUE (KNOWN PNULL)]',
        '$heap_graph(S_byte) = H',
        '$drive_steps(S, 0) = S[.COMPLETION = BUDGET]',
        '$drive_steps(S, 1) = S_byte[.COMPLETION = BUDGET]',
        *guards('S_byte'),
    ]
    return (HELPERS + '\ndec $main() : bool\ndef $main() = true\n' + ''.join(
        '  -- ' + (check if check.startswith('PhpStep:') else 'if ' + check) + '\n'
        for check in checks), len(checks), derived_count)
