        '~$string_read_release_tasks((CONCAT_RIGHT (KNOWN pkeyread.BASE) false false 22) :: ptask_tail*)',
        '~$string_read_cast_released(S_owned_tail, pstringread)',
        # Registration masks own no additional bytes; active-callback scope stays.
        '$string_read_cast_released(S[.ERRORHANDLER.LEVELS = 0], pstringread)',
        '$string_read_cast_released(S[.ERRORHANDLERS = eps], pstringread)',
        '$string_read_cast_released(S[.ERRORHANDLERS = S.ERRORHANDLERS ++ S.ERRORHANDLERS], pstringread)',
        '~$string_read_cast_released(S[.ERRORHANDLER.CALLBACK = eps], pstringread)',
        '~$string_read_cast_released(S[.ERRORHANDLERS = [{CALLBACK (PNULL), LEVELS 0}]], pstringread)',
        # Normal resumption adds no authority to pending-Throwable discard.
        '$string_read_discard(S, pstringread) = S[.COMPLETION = UNSUPPORTED "string offset borrowed carrier after callback"]',
        'S_pending = S[.TODO = (THROW_SEARCH 0) :: ptask_tail*]',
        '~$string_read_cast_released(S_pending, pstringread)',
        '$string_read_discard(S_pending, pstringread) = S_pending[.COMPLETION = UNSUPPORTED "string offset borrowed carrier after callback"]',
        # A known key cannot replace the genuine raw CV source.
        '$origin_child((pkeyread.SITE), [PCFIELD 1]) = (porigin_key)',
        '$compiled_read(S, porigin_key) = eps',
        'pstringread_literal = pstringread[.READ.INPUT = KNOWN (PBOOL true)][.KEYCELL = eps]',
        'S_literal = S[.TODO = (STRING_READ_RESULT pstringread_literal) :: ptask_tail*]',
        '~$string_read_source(S_literal, pstringread_literal)',
        '~$string_read_cast_released(S_literal, pstringread_literal)',
        # NUL validity and source authentication alone never authorize this lane.
        'pvalue_nul = PSTRING_CARRIER (REQUEST_STRING 0) ([97,0,98,99])',
        'pstringread_nul = pstringread[.READ.BASE = pvalue_nul]',
        'S_nul = S[.STRINGDATA = [[97,0,98,99]]][.STORE[n_original] = DEFINED pvalue_nul][.TODO = (STRING_READ_RESULT pstringread_nul) :: ptask_tail*]',
