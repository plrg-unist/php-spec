        'S.RESULT = perrorread.INPUT',
        '$' + shape + '(perrorread.ORIGINAL,perrorread.INPUT,perrorread.BASE) = (perrorread)',
        'perrorread.NAME = $ptascii("missing")', 'perrorread.LINE = ' + str(line),
