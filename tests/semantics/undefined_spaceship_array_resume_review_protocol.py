        '$lookup(S_resume.ENV,$ptascii("copy")) = (n_copy_cell)',
        'S_resume.STORE[n_copy_cell] = DEFINED (PARRAY n_copy)',
        'n_live =/= n_copy', '(HARRAY n_live) <- S_resume.ALLOCATIONS',
        '(HARRAY n_copy) <- S_resume.ALLOCATIONS',
        '~$array_immutable(S_resume,n_live)', '~$array_immutable(S_resume,n_copy)',
        'S_resume.ARRAYS[n_live].NEXT = 1',
        'S_resume.ARRAYS[n_copy].ITEMS = [ENTRY (KINT 0) (DIRECT (PINT ' + str(copy_value) + '))]',
        'S_resume.ARRAYS[n_copy].NEXT = 1',
        '$heap_owners($heap_prune($heap_graph(S_resume)),HCELL n_current) = 2',
        '$heap_owners($heap_prune($heap_graph(S_resume)),HARRAY n_live) = 1',
        'n_copy_pool = $heap_count(HARRAY n_copy,$pools_nodes(S_resume.POOLS))',
        '$heap_owners($heap_prune($heap_graph(S_resume)),HARRAY n_copy) = $(1 + n_copy_pool)',
        '$lookup(S_resume.ENV,$ptascii("missing")) = (n_missing)',
        'S_resume.STORE[n_missing] = DEFINED (PINT 9)',
