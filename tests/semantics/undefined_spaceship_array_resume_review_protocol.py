from undefined_spaceship_protocol import PREFIX, text


def checks(program, path, name):
    rebound = name == 'peer-array-right-missing-rebound-reference-default'
    line, left_line = (17, 17) if rebound else (18, 17)
    current, alias = ('left', 'replacement') if rebound else ('right', 'slot')
    left, right = ('left', 'missing') if rebound else ('missing', 'right')
