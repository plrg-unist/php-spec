        '~$spaceship_read_array(S_resume,perrorread_opposite)',
        '~$spaceship_read_again(S_resume,perrorread)', '~$spaceship_checked_missing(S_resume,perrorread)',
        'S_resume.EVENTS = S_return.EVENTS' + (' ++ [$error_default_event(S_return,WARNING ($ptascii("missing")) 17)]' if rebound else ''),
