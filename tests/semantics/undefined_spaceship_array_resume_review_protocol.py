    original = 'BINARY_RIGHT SPACESHIP (VARIABLE (' + text(left) + ') z_left) ' + str(line)
    task = original if rebound else 'BINARY_RIGHT SPACESHIP (KNOWN PNULL) ' + str(line)
    answer, copy_value = (1, 8) if rebound else (0, 7)
    expected = ('H:1:1:17:1;R:1:1:1:1:1:1:1;A:1:1:1;END;' if rebound else
                'H:1:1:18:1;R:1:1:1:1:1:1;A:1:1:1;END;')
