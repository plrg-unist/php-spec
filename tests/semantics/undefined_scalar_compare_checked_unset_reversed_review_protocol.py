"""Independent right-first quiet CV loss, aliases and the unread-left boundary."""
import base64
import json

from undefined_spaceship_protocol import PREFIX as COMMON, text

PREFIX = COMMON.replace('BINARY_RIGHT SPACESHIP poperand z',
                        'BINARY_RIGHT pbin poperand z\n  -- if pbin = GREATER \\/ pbin = GREATEREQUAL')


def checks(program, path, name):
    target = name == 'peer-checked-greater-unset-target-default'
    operator, boolean, line = ('GREATER', 'false', 15) if target else ('GREATEREQUAL', 'true', 16)
    expected = ('H:1:1:15:1;R:1:1:1:1:1;A:1:1;END;' if target else
                'H:1:1:16:1;R:1:1:1:1:1;A:1:1:1;END;')
    original = 'BINARY_RIGHT ' + operator + ' (VARIABLE ($ptascii("missing")) z_left) ' + str(line)
    frozen = 'BINARY_RIGHT ' + operator + ' (KNOWN PNULL) ' + str(line)
    values = [
        'S_initial = $php_run(' + program + ',0,' + json.dumps(base64.b64encode(str(path).encode()).decode()) + ')',
        'S_initial.COMPLETION = BUDGET',
        'S_found = $us_seek(S_initial,0,1200)',
        r'S_found.COMPLETION = NORMAL \/ S_found.COMPLETION = BUDGET',
        'S = S_found[.COMPLETION = NORMAL]', '$us_stage(S,0)', '$us_guard(S)',
        '$error_read_plan(S) = (perrorread)', '$error_read_valid(S,perrorread)',
        '$error_read_shape(perrorread.ORIGINAL,perrorread.INPUT,perrorread.BASE) = (perrorread)',
        'perrorread.ORIGINAL = ' + original,
        'perrorread.INPUT = VARIABLE ($ptascii("right")) z_right',
        'perrorread.NAME = $ptascii("missing")', 'perrorread.LINE = ' + str(line),
        'perrorread.TASK = ' + frozen, 'perrorread.RESULT = perrorread.INPUT',
        'S.TODO = perrorread.ORIGINAL :: ptask_tail*', 'S.RESULT = perrorread.INPUT',
        '$scalar_compare_read_other(S,perrorread)',
        '~$scalar_compare_checked_right_missing(S,perrorread)',
        '~$scalar_compare_checked_missing(S,perrorread)',
        '~$scalar_compare_read_again(S,perrorread)',
        '$task_nodes(ERROR_READ_RESULT perrorread) = eps',
        '$lookup(S.ENV,$ptascii("right")) = (n_original)',
        'S.STORE[n_original] = DEFINED pvalue_original',
        '$string_plain(pvalue_original) = PSTRING ($ptascii("0"))',
        'S.ORIGIN = (porigin)',
        '$code_expression_at_source(S,porigin,[PCFIELD 0]) = (15)',
        '$code_expression_at_source(S,porigin,[PCFIELD 1]) = (' + str(line) + ')',
        '$scalar_compare_right_read_shape(perrorread.ORIGINAL,perrorread.INPUT,perrorread.BASE) = (perrorread_right)',
        'perrorread_right =/= perrorread',
        'S_warn_pause = $drive_steps(S,1)', 'S_warn_pause.COMPLETION = BUDGET',
        'S_warn = S_warn_pause[.COMPLETION = NORMAL]', '$us_stage(S_warn,1)',
        'S_warn = $prune_allocations($error_read_begin(S))',
        'S_warn.TODO = (ERROR_HANDLER_INVOKE perrorcall) :: ptask_tail*',
        'perrorcall.RESUME = ERROR_READ_RESULT perrorread',
        'perrorcall.LEVEL = 2', 'perrorcall.LINE = ' + str(line),
        'perrorcall.MESSAGE = $ptascii("Undefined variable $missing")',
        'perrorcall.EVENT = WARNING ($ptascii("missing")) ' + str(line),
        '$error_call_valid(S_warn,perrorcall)',
        'S_warn.EVENTS = S.EVENTS', '$us_guard(S_warn)',
        'S_return_found = $us_seek(S_warn,2,1200)',
        r'S_return_found.COMPLETION = NORMAL \/ S_return_found.COMPLETION = BUDGET',
        'S_return = S_return_found[.COMPLETION = NORMAL]',
        'S_return.TODO = (ERROR_HANDLER_RESULT perrorcall_entered) :: ptask_tail*',
        'perrorcall_entered.RESUME = ERROR_READ_RESULT perrorread',
        '$call_task_valid(S_return,ERROR_HANDLER_RESULT perrorcall_entered)',
        r'S_return.CURRENT = eps /\ S_return.FRAMES = eps', '$us_guard(S_return)',
        'S_return.RESULT = KNOWN (PBOOL ' + ('false' if target else 'true') + ')',
        'S_resume_found = $us_seek(S_return,3,1200)',
        r'S_resume_found.COMPLETION = NORMAL \/ S_resume_found.COMPLETION = BUDGET',
        'S_resume = S_resume_found[.COMPLETION = NORMAL]', '$us_stage(S_resume,3)',
        'S_resume.TODO = (ERROR_READ_RESULT perrorread) :: ptask_tail*',
        '$error_read_valid(S_resume,perrorread)',
        '~$scalar_compare_read_other(S_resume,perrorread)',
        '$scalar_compare_checked_right_missing(S_resume,perrorread)',
        '~$scalar_compare_checked_missing(S_resume,perrorread)',
        '~$scalar_compare_read_again(S_resume,perrorread)',
        '$lookup(S_resume.ENV,$ptascii("right")) = eps',
        '$lookup(S_resume.ENV,$ptascii("missing")) = (n_missing)',
        'S_resume.STORE[n_missing] = DEFINED (PINT 9)',
        'S_resume.ERRORHANDLER = S.ERRORHANDLER', '$us_guard(S_resume)',
        'S_resume.EVENTS = S_return.EVENTS' + (' ++ [$error_default_event(S_return,WARNING ($ptascii("missing")) 15)]' if target else ''),
        'PhpStep: S_resume ~> S_restored',
        'S_restored = S_resume[.TODO = perrorread.TASK :: ptask_tail*][.RESULT = KNOWN PNULL][.BASE = perrorread.BASE]',
        '$error_read_plan(S_restored) = eps',
        'PhpStep: S_restored ~> S_compared',
        'S_compared = S_restored[.TODO = ptask_tail*][.RESULT = KNOWN (PBOOL ' + boolean + ')][.BASE = BASE_VALUE (KNOWN PNULL)]',
        'S_compared.EVENTS = S_resume.EVENTS', '$us_guard(S_compared)',
        'S_done = $drive_steps(S_compared,4000)', 'S_done.COMPLETION = NORMAL',
        r'S_done.TODO = eps /\ S_done.CURRENT = eps /\ S_done.FRAMES = eps',
        '$us_output(S_done.EVENTS) = ' + text(expected), '$us_guard(S_done)',
        'S_done.CODE = S_initial.CODE', 'S_done.POOLS = S_initial.POOLS',
        'S_done = $drive_steps(S_initial[.COMPLETION = NORMAL],4000)',
        '$drive_steps(S_warn_pause[.COMPLETION = NORMAL],4000) = S_done',
        '$drive_steps(S_return,4000) = S_done',
        'S_zero = $drive_steps(S_resume,0)', 'S_zero = S_resume[.COMPLETION = BUDGET]',
        '$drive_steps(S_zero[.COMPLETION = NORMAL],4000) = S_done',
        'perrorread_bad = perrorread[.ORIGINAL = BINARY_RIGHT ' + operator + ' (VARIABLE ($ptascii("missing")) 999) ' + str(line) + ']',
        '$error_read_shape(perrorread_bad.ORIGINAL,perrorread_bad.INPUT,perrorread_bad.BASE) = (perrorread_bad)',
        '$scalar_compare_checked_right_missing(S_resume,perrorread_bad)',
        '~$error_read_valid(S_resume,perrorread_bad)',
        '~$error_call_valid(S_warn,perrorcall[.RESUME = ERROR_READ_RESULT perrorread_bad])',
        'perrorread_line = perrorread[.ORIGINAL = BINARY_RIGHT ' + operator + ' (VARIABLE ($ptascii("missing")) z_left) 999][.TASK = BINARY_RIGHT ' + operator + ' (KNOWN PNULL) 999][.LINE = 999]',
        '$scalar_compare_checked_right_missing(S_resume,perrorread_line)',
        '~$error_read_valid(S_resume,perrorread_line)',
        'perrorread_input = perrorread[.INPUT = VARIABLE ($ptascii("foreign")) 999][.RESULT = VARIABLE ($ptascii("foreign")) 999]',
        '$error_read_shape(perrorread_input.ORIGINAL,perrorread_input.INPUT,perrorread_input.BASE) = (perrorread_input)',
        '$scalar_compare_checked_right_missing(S_resume,perrorread_input)',
        '~$error_read_valid(S_resume,perrorread_input)',
        '~$error_read_valid(S_resume[.CODE = eps],perrorread)',
        '~$error_read_valid(S_resume[.ORIGIN = eps],perrorread)',
        'perrorread_forward = perrorread[.ORIGINAL = BINARY_RIGHT EQUAL (VARIABLE ($ptascii("missing")) z_left) ' + str(line) + '][.TASK = BINARY_RIGHT EQUAL (KNOWN PNULL) ' + str(line) + ']',
        '~$scalar_compare_checked_right_missing(S_resume,perrorread_forward)',
        '~$error_read_valid(S_resume,perrorread_forward)',
        '~$scalar_compare_checked_right_missing(S_resume,perrorread_right)',
        'S_both = $unset_name(S_resume,$ptascii("missing"))', '$us_guard(S_both)',
        '$scalar_compare_checked_right_missing(S_both,perrorread)',
        '$scalar_compare_read_again(S_both,perrorread_right)',
        '~$scalar_compare_checked_right_missing(S_both,perrorread_right)',
        '$error_read_plan(S_both[.TODO = perrorread.ORIGINAL :: ptask_tail*][.RESULT = perrorread.INPUT][.BASE = perrorread.BASE]) = (perrorread_right)',
        'S_unchecked = S_both[.TODO = (ERROR_READ_RESULT perrorread_right) :: ptask_tail*]',
        '$error_read_valid(S_unchecked,perrorread_right)',
        'PhpStep: S_unchecked ~> S_unchecked_restored',
        'S_unchecked_restored = S_unchecked[.TODO = perrorread_right.TASK :: ptask_tail*][.RESULT = perrorread_right.RESULT][.BASE = perrorread_right.BASE]',
        '$error_read_plan(S_unchecked_restored) = (perrorread_later)',
        'perrorread_later.NAME = $ptascii("missing")',
        'perrorread_later.INPUT = KNOWN PNULL',
        '~$scalar_compare_checked_right_missing(S_unchecked_restored,perrorread_later)',
    ]
    if target:
        values += [
            '$lookup(S.ENV,$ptascii("target")) = (n_original)',
            'n_original <- S.REFCELLS',
            '$heap_owners($heap_prune($heap_graph(S)),HCELL n_original) = 2',
            '$lookup(S_resume.ENV,$ptascii("target")) = (n_original)',
            'S_resume.STORE[n_original] = DEFINED (PINT 8)',
            '$heap_owners($heap_prune($heap_graph(S_resume)),HCELL n_original) = 1',
            '$lookup(S_done.ENV,$ptascii("target")) = (n_original)',
            '$lookup(S_done.ENV,$ptascii("right")) = (n_original)',
            'S_done.STORE[n_original] = DEFINED (PINT 6)',
            '$heap_owners($heap_prune($heap_graph(S_done)),HCELL n_original) = 2',
        ]
    else:
        values += [
            '~(n_original <- S.REFCELLS)',
            '$heap_owners($heap_prune($heap_graph(S)),HCELL n_original) = 1',
            '$lookup(S_resume.ENV,$ptascii("alias")) = (n_original)',
            'n_original <- S_resume.REFCELLS',
            'S_resume.STORE[n_original] = DEFINED pvalue_original',
            '$heap_owners($heap_prune($heap_graph(S_resume)),HCELL n_original) = 1',
            '$lookup(S_done.ENV,$ptascii("alias")) = (n_original)',
            '$lookup(S_done.ENV,$ptascii("right")) = eps',
            'S_done.STORE[n_original] = DEFINED (PINT 5)',
            '$heap_owners($heap_prune($heap_graph(S_done)),HCELL n_original) = 1',
        ]
    return values
