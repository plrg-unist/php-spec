"""Independent quiet checked-CV loss, surviving aliases and unread-CV checks."""
import base64
import json

from undefined_spaceship_protocol import PREFIX, text


def checks(program, path, name):
    reference = name == 'peer-checked-reference-unset-default'
    expected = ('H:1:1:15:1;R:1:1:1:1:1;A:1:1;END;' if reference
                else 'H:1:1:15:1;R:1:1:1:1;END;')
    values = [
        'S_initial = $php_run(' + program + ',0,' + json.dumps(base64.b64encode(str(path).encode()).decode()) + ')',
        'S_initial.COMPLETION = BUDGET',
        'S_found = $us_seek(S_initial,0,1200)',
        r'S_found.COMPLETION = NORMAL \/ S_found.COMPLETION = BUDGET',
        'S = S_found[.COMPLETION = NORMAL]', '$us_stage(S,0)', '$us_guard(S)',
        '$error_read_plan(S) = (perrorread)', '$error_read_valid(S,perrorread)',
        '$spaceship_right_read_shape(perrorread.ORIGINAL,perrorread.INPUT,perrorread.BASE) = (perrorread)',
        'perrorread.ORIGINAL = BINARY_RIGHT SPACESHIP (VARIABLE ($ptascii("left")) z_left) 15',
        'perrorread.INPUT = VARIABLE ($ptascii("missing")) z_right',
        'perrorread.NAME = $ptascii("missing")', 'perrorread.LINE = 15',
        'perrorread.TASK = perrorread.ORIGINAL', 'perrorread.RESULT = KNOWN PNULL',
        'S.TODO = perrorread.ORIGINAL :: ptask_tail*', 'S.RESULT = perrorread.INPUT',
        '$spaceship_read_other(S,perrorread)',
        '~$spaceship_checked_missing(S,perrorread)',
        '~$spaceship_read_again(S,perrorread)',
        '$task_nodes(ERROR_READ_RESULT perrorread) = eps',
        '$lookup(S.ENV,$ptascii("left")) = (n_original)',
        'S.STORE[n_original] = DEFINED pvalue_original',
        '$string_plain(pvalue_original) = PSTRING ($ptascii("0"))',
        'S.ORIGIN = (porigin)',
        '$code_expression_at_source(S,porigin,[PCFIELD 0]) = (' + ('15' if reference else '14') + ')',
        '$code_expression_at_source(S,porigin,[PCFIELD 1]) = (15)',
        '$error_read_shape(perrorread.ORIGINAL,perrorread.INPUT,perrorread.BASE) = (perrorread_left)',
        'perrorread_left =/= perrorread',
        'S_warn_pause = $drive_steps(S,1)', 'S_warn_pause.COMPLETION = BUDGET',
        'S_warn = S_warn_pause[.COMPLETION = NORMAL]', '$us_stage(S_warn,1)',
        'S_warn = $prune_allocations($error_read_begin(S))',
        'S_warn.TODO = (ERROR_HANDLER_INVOKE perrorcall) :: ptask_tail*',
        'perrorcall.RESUME = ERROR_READ_RESULT perrorread',
        'perrorcall.LEVEL = 2', 'perrorcall.LINE = 15',
        'perrorcall.MESSAGE = $ptascii("Undefined variable $missing")',
        'perrorcall.EVENT = WARNING ($ptascii("missing")) 15',
        '$error_call_valid(S_warn,perrorcall)',
        'S_warn.EVENTS = S.EVENTS', '$us_guard(S_warn)',
        'S_return_found = $us_seek(S_warn,2,1200)',
        r'S_return_found.COMPLETION = NORMAL \/ S_return_found.COMPLETION = BUDGET',
        'S_return = S_return_found[.COMPLETION = NORMAL]',
        'S_return.TODO = (ERROR_HANDLER_RESULT perrorcall_entered) :: ptask_tail*',
        'perrorcall_entered.RESUME = ERROR_READ_RESULT perrorread',
        '$call_task_valid(S_return,ERROR_HANDLER_RESULT perrorcall_entered)',
        r'S_return.CURRENT = eps /\ S_return.FRAMES = eps', '$us_guard(S_return)',
        'S_return.RESULT = KNOWN (PBOOL ' + ('false' if reference else 'true') + ')',
        'S_resume_found = $us_seek(S_return,3,1200)',
        r'S_resume_found.COMPLETION = NORMAL \/ S_resume_found.COMPLETION = BUDGET',
        'S_resume = S_resume_found[.COMPLETION = NORMAL]', '$us_stage(S_resume,3)',
        'S_resume.TODO = (ERROR_READ_RESULT perrorread) :: ptask_tail*',
        '$error_read_valid(S_resume,perrorread)',
        '~$spaceship_read_other(S_resume,perrorread)',
        '$spaceship_checked_missing(S_resume,perrorread)',
        '~$spaceship_read_again(S_resume,perrorread)',
        '$lookup(S_resume.ENV,$ptascii("left")) = eps',
        '$lookup(S_resume.ENV,$ptascii("missing")) = (n_missing)',
        'S_resume.STORE[n_missing] = DEFINED (PINT 9)',
        'S_resume.ERRORHANDLER = S.ERRORHANDLER', '$us_guard(S_resume)',
        'S_resume.EVENTS = S_return.EVENTS' + (' ++ [$error_default_event(S_return,WARNING ($ptascii("missing")) 15)]' if reference else ''),
        'PhpStep: S_resume ~> S_restored',
        'S_restored = S_resume[.TODO = (BINARY_RIGHT SPACESHIP (KNOWN PNULL) 15) :: ptask_tail*][.RESULT = KNOWN PNULL][.BASE = perrorread.BASE]',
        '$error_read_plan(S_restored) = eps',
        'PhpStep: S_restored ~> S_compared',
        'S_compared = S_restored[.TODO = ptask_tail*][.RESULT = KNOWN (PINT 0)][.BASE = BASE_VALUE (KNOWN PNULL)]',
        'S_compared.EVENTS = S_resume.EVENTS', '$us_guard(S_compared)',
        'S_done = $drive_steps(S_compared,4000)', 'S_done.COMPLETION = NORMAL',
        r'S_done.TODO = eps /\ S_done.CURRENT = eps /\ S_done.FRAMES = eps',
        '$us_output(S_done.EVENTS) = ' + text(expected), '$us_guard(S_done)',
        'S_done.CODE = S_initial.CODE', 'S_done.POOLS = S_initial.POOLS',
        'S_done = $drive_steps(S_initial[.COMPLETION = NORMAL],4000)',
        '$drive_steps(S_warn_pause[.COMPLETION = NORMAL],4000) = S_done',
        '$drive_steps(S_return,4000) = S_done',
        'S_zero = $drive_steps(S_resume,0)', 'S_zero = S_resume[.COMPLETION = BUDGET]',
        '$drive_steps(S_zero[.COMPLETION = NORMAL],4000) = S_done',
        'perrorread_bad = perrorread[.ORIGINAL = BINARY_RIGHT SPACESHIP (VARIABLE ($ptascii("left")) 999) 15][.TASK = BINARY_RIGHT SPACESHIP (VARIABLE ($ptascii("left")) 999) 15]',
        '$spaceship_right_read_shape(perrorread_bad.ORIGINAL,perrorread_bad.INPUT,perrorread_bad.BASE) = (perrorread_bad)',
        '$spaceship_checked_missing(S_resume,perrorread_bad)',
        '~$error_read_valid(S_resume,perrorread_bad)',
        '~$error_call_valid(S_warn,perrorcall[.RESUME = ERROR_READ_RESULT perrorread_bad])',
        'perrorread_line = perrorread[.ORIGINAL = BINARY_RIGHT SPACESHIP (VARIABLE ($ptascii("left")) z_left) 999][.TASK = BINARY_RIGHT SPACESHIP (VARIABLE ($ptascii("left")) z_left) 999][.LINE = 999]',
        '$spaceship_checked_missing(S_resume,perrorread_line)',
        '~$error_read_valid(S_resume,perrorread_line)',
        '~$error_read_valid(S_resume[.CODE = eps],perrorread)',
        '~$error_read_valid(S_resume[.ORIGIN = eps],perrorread)',
        'perrorread_equal = perrorread[.ORIGINAL = BINARY_RIGHT EQUAL (VARIABLE ($ptascii("left")) z_left) 15][.TASK = BINARY_RIGHT EQUAL (VARIABLE ($ptascii("left")) z_left) 15]',
        '~$spaceship_checked_missing(S_resume,perrorread_equal)',
        '~$error_read_valid(S_resume,perrorread_equal)',
        '~$spaceship_checked_missing(S_resume,perrorread_left)',
        'S_both_missing = $unset_name(S_resume,$ptascii("missing"))',
        '$us_guard(S_both_missing)',
        '$spaceship_checked_missing(S_both_missing,perrorread)',
        '$spaceship_read_again(S_both_missing,perrorread_left)',
        '~$spaceship_checked_missing(S_both_missing,perrorread_left)',
        '$error_read_plan(S_both_missing[.TODO = perrorread.ORIGINAL :: ptask_tail*][.RESULT = perrorread.INPUT][.BASE = perrorread.BASE]) = (perrorread_left)',
        'S_unchecked = S_both_missing[.TODO = (ERROR_READ_RESULT perrorread_left) :: ptask_tail*]',
        '$error_read_valid(S_unchecked,perrorread_left)',
        'PhpStep: S_unchecked ~> S_unchecked_restored',
        'S_unchecked_restored = S_unchecked[.TODO = perrorread_left.TASK :: ptask_tail*][.RESULT = perrorread_left.RESULT][.BASE = perrorread_left.BASE]',
        '$error_read_plan(S_unchecked_restored) = (perrorread_later)',
        'perrorread_later.NAME = $ptascii("missing")',
        '~$spaceship_checked_missing(S_unchecked_restored,perrorread_later)',
    ]
    if reference:
        values += [
            '$lookup(S.ENV,$ptascii("target")) = (n_original)',
            'n_original <- S.REFCELLS',
            '$heap_owners($heap_prune($heap_graph(S)),HCELL n_original) = 2',
            '$lookup(S_resume.ENV,$ptascii("target")) = (n_original)',
            'S_resume.STORE[n_original] = DEFINED (PINT 8)',
            '$heap_owners($heap_prune($heap_graph(S_resume)),HCELL n_original) = 1',
            '$lookup(S_done.ENV,$ptascii("target")) = (n_original)',
            '$lookup(S_done.ENV,$ptascii("left")) = (n_original)',
            'S_done.STORE[n_original] = DEFINED (PINT 6)',
            '$heap_owners($heap_prune($heap_graph(S_done)),HCELL n_original) = 2',
        ]
    else:
        values += [
            '~(n_original <- S.REFCELLS)',
            '$heap_owners($heap_prune($heap_graph(S)),HCELL n_original) = 1',
            '$heap_owners($heap_prune($heap_graph(S_resume)),HCELL n_original) = 0',
            '$lookup(S_done.ENV,$ptascii("left")) = eps',
        ]
    return values
