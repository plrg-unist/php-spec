"""Distinguish an equal-byte live header from a retired borrowed header."""
import json

from string_offset_request_release_prior_cv_peer_review import HELPERS, seek
from string_offset_undefined_cv_review import guards


def render(program, filename_b64):
    checks = [
        'S_initial = $php_run(' + program + ', 0, ' + json.dumps(filename_b64) + ')',
        'S_initial.COMPLETION = BUDGET',
    ] + seek('S_initial', 2, 'S_start') + [
        'S_start.TODO = (ERROR_HANDLER_INVOKE perrorcall_start) :: ptask_start*',
        'perrorcall_start.RESUME = KEY_READ_RESULT pkeyread',
        'pkeyread.BASE = PSTRING_CARRIER (REQUEST_STRING 0) ($ptascii("abc"))',
        'pkeyread.OWNERS = BASE_VALUE (VARIABLE n_base_name* z_base)',
        'n_base_name* = $ptascii("base")',
        '$lookup(S_start.ENV, n_base_name*) = (n_original)',
        '$lookup(S_start.ENV, $ptascii("keeper")) = (n_keeper)',
        '$lookup(S_start.ENV, $ptascii("bystander")) = (n_bystander)',
        '$lookup(S_start.ENV, $ptascii("got")) = (n_got)',
        r'n_original = 2 /\ n_keeper = 3 /\ n_bystander = 4 /\ n_got = 5',
        'pvalue_bystander = PSTRING_CARRIER (REQUEST_STRING 1) ($ptascii("abc"))',
        'S_start.STORE[n_original] = DEFINED pkeyread.BASE',
        'S_start.STORE[n_keeper] = DEFINED pkeyread.BASE',
        'S_start.STORE[n_bystander] = DEFINED pvalue_bystander',
        '$string_carrier_valid(S_start, pvalue_bystander)',
        '$heap_owners($heap_graph(S_start), HCELL n_original) = 1',
        '$heap_owners($heap_graph(S_start), HCELL n_keeper) = 1',
        '$heap_owners($heap_graph(S_start), HCELL n_bystander) = 1',
        '$error_call_valid(S_start, perrorcall_start)',
    ] + seek('S_start', 0, 'S_before') + [
        'S_before.TODO = (ERROR_HANDLER_INVOKE perrorcall_cast) :: ptask_tail*',
        'perrorcall_cast.RESUME = STRING_READ_RESULT pstringread',
        'pstringread = {READ pkeyread, BASECELL eps, KEYCELL eps, PHASE STRING_CAST}',
        r'S_before.CURRENT = eps /\ S_before.FRAMES = eps',
        r'pkeyread.PHASE = KEY_CV /\ pkeyread.VALUE = PNULL',
        'pkeyread.NAME = $ptascii("key")',
        'pkeyread.INPUT = VARIABLE pkeyread.NAME 29',
        r'pkeyread.LINE = 29 /\ pkeyread.KEY = KSTRING eps',
        '$lookup(S_before.ENV, n_base_name*) = (n_base)',
        '$lookup(S_before.ENV, pkeyread.NAME) = (n_key)',
        r'n_base = 11 /\ n_key = 12',
        'S_before.STORE[n_base] = DEFINED (PINT 99)',
        'S_before.STORE[n_key] = DEFINED (PINT 4)',
        'S_before.STORE[n_bystander] = DEFINED pvalue_bystander',
        '~((HCELL n_original) <- S_before.ALLOCATIONS)',
        'S_before.STORE[n_keeper] = DEFINED pkeyread.BASE',
        '$string_read_source(S_before, pstringread)',
        '$string_read_provider_ready(S_before, pstringread)',
        '~$string_read_cv_released(S_before, pkeyread)',
        '$error_call_valid(S_before, perrorcall_cast)',
        'H_before = $heap_graph(S_before)',
        'H_before.NODES = [HCELL 0, HCELL 1, HCELL 3, HCELL 4, HCELL 5, HCELL 11, HCELL 12]',
        'H_before.ROOTS = [HCELL 12, HCELL 11, HCELL 5, HCELL 4, HCELL 3, HCELL 1, HCELL 0]',
        r'H_before.EDGES = eps /\ H_before.DEBTS = eps',
        '$heap_owners(H_before, HCELL n_keeper) = 1',
    ] + seek('S_before', 1, 'S') + [
        'S.TODO = (STRING_READ_RESULT pstringread) :: ptask_tail*',
        r'S.CURRENT = eps /\ S.FRAMES = eps',
        'S.ENV = [BIND ($ptascii("key")) n_key, BIND n_base_name* n_base, BIND ($ptascii("got")) n_got, BIND ($ptascii("bystander")) n_bystander, BIND ($ptascii("right")) 1, BIND ($ptascii("left")) 0]',
        'S.STORE[n_original] = DEFINED pkeyread.BASE',
        'S.STORE[n_keeper] = DEFINED pkeyread.BASE',
        r'~((HCELL n_original) <- S.ALLOCATIONS) /\ ~((HCELL n_keeper) <- S.ALLOCATIONS)',
        'S.STORE[n_bystander] = DEFINED pvalue_bystander',
        'S.STORE[n_got] = DEFINED (PINT 99)',
        'S.STORE[n_base] = DEFINED (PINT 99)',
        'S.STORE[n_key] = DEFINED (PINT 8)',
        'S.REFCELLS = [n_base]',
        'S.STRINGDATA = [$ptascii("abc"), $ptascii("abc")]',
        'S.ERRORHANDLER = {CALLBACK (perrorcall_cast.CALLBACK), LEVELS 30719}',
        'S.ERRORHANDLERS = [{CALLBACK (PSTRING_CARRIER INTERNED_STRING ($ptascii("requestReleasePrior"))), LEVELS 2}, {CALLBACK eps, LEVELS 0}]',
        '$error_handler_roots(S.ERRORHANDLER) = eps',
        '$error_handler_stack_roots(S.ERRORHANDLERS) = eps',
        'S.EVENTS = S_before.EVENTS ++ [OUTPUT ($ptascii("2")), OUTPUT ($ptascii(":")), OUTPUT ($ptascii("String offset cast occurred")), OUTPUT ($ptascii(";"))]',
        'S.RESULT = KNOWN PNULL',
        'S.BASE = BASE_VALUE (KNOWN PNULL)',
        '$string_read_source(S, pstringread)',
        '~$string_read_provider_ready(S, pstringread)',
        '$string_read_cv_plan(S, pkeyread) = eps',
        '$string_carrier_valid(S, pvalue_bystander)',
        '$string_read_release_cells(S, 0, S.ALLOCATIONS)',
        '$string_read_cv_released(S, pkeyread)',
        'H = $heap_graph(S)',
        'H.NODES = [HCELL 0, HCELL 1, HCELL 4, HCELL 5, HCELL 11, HCELL 12]',
        'H.ROOTS = [HCELL 12, HCELL 11, HCELL 5, HCELL 4, HCELL 1, HCELL 0]',
        r'H.EDGES = eps /\ H.DEBTS = eps',
        '$heap_owners(H, HCELL n_original) = 0',
        '$heap_owners(H, HCELL n_keeper) = 0',
        '$heap_owners(H, HCELL n_bystander) = 1',
        '$heap_valid(H_before)',
        '$task_nodes(STRING_READ_RESULT pstringread) = eps',
        *guards('S'),
        'S_expected = S[.TODO = ptask_tail*][.RESULT = KNOWN PNULL][.BASE = BASE_VALUE (KNOWN PNULL)]',
        '$string_read_resume(S, pstringread) = S_expected',
        'PhpStep: S ~> S_after',
        'S_after = S_expected',
        '$heap_graph(S_after) = H',
        'S_after.EVENTS = S.EVENTS',
        'S_after.STORE[n_bystander] = DEFINED pvalue_bystander',
        '$drive_steps(S, 0) = S[.COMPLETION = BUDGET]',
        '$drive_steps(S, 1) = S_expected[.COMPLETION = BUDGET]',
        '$drive_steps(S_expected, 1) = $drive_steps(S, 2)',
    ]
    derived_start = len(checks)
    checks += [
        # A different header stays distinct even through a live reference cell.
        'S_distinct_marked = S[.REFCELLS = n_bystander :: S.REFCELLS]',
        '$heap_valid($heap_graph(S_distinct_marked))',
        '$call_reference_operand_valid(S_distinct_marked, REFERENCE n_bystander)',
        '$string_read_cv_released(S_distinct_marked, pkeyread)',
        '$string_read_resume(S_distinct_marked, pstringread) = S_distinct_marked[.TODO = ptask_tail*][.RESULT = KNOWN PNULL][.BASE = BASE_VALUE (KNOWN PNULL)]',
        # Equal bytes with the selected identity restore a real owner.
        'S_same = S[.STORE[n_bystander] = DEFINED pkeyread.BASE]',
        '$string_read_source(S_same, pstringread)',
        '$string_read_provider_ready(S_same, pstringread)',
        '~$string_read_cv_released(S_same, pkeyread)',
        'S_same_marked = S_same[.REFCELLS = n_bystander :: S.REFCELLS]',
        '$heap_valid($heap_graph(S_same_marked))',
        '$heap_owners($heap_graph(S_same_marked), HCELL n_bystander) = 1',
        '$string_read_source(S_same_marked, pstringread)',
        '~$string_read_provider_ready(S_same_marked, pstringread)',
        '~$string_read_cv_released(S_same_marked, pkeyread)',
        'PhpStep: S_same_marked ~> S_same_refused',
        'S_same_refused = S_same_marked[.COMPLETION = UNSUPPORTED "string offset borrowed carrier after callback"]',
        '$heap_graph(S_same_refused) = $heap_graph(S_same_marked)',
        # A different identifier needs its own exact, non-NUL registry payload.
        '~$string_read_cv_released(S[.STORE[n_bystander] = DEFINED (PSTRING ($ptascii("abc")))], pkeyread)',
        '~$string_read_cv_released(S[.STORE[n_bystander] = DEFINED (PSTRING_CARRIER (REQUEST_STRING 2) ($ptascii("abc")))], pkeyread)',
        '~$string_read_cv_released(S[.STRINGDATA[1] = $ptascii("abd")], pkeyread)',
        '~$string_read_cv_released(S[.STORE[n_bystander] = DEFINED (PSTRING_CARRIER (REQUEST_STRING 1) ($ptascii("abd")))], pkeyread)',
        'S_nul = S[.STRINGDATA = S.STRINGDATA ++ [[97, 0]]][.STORE[n_bystander] = DEFINED (PSTRING_CARRIER (REQUEST_STRING 2) ([97, 0]))]',
        '$string_carrier_valid(S_nul, PSTRING_CARRIER (REQUEST_STRING 2) ([97, 0]))',
        '~$string_read_cv_released(S_nul, pkeyread)',
        # A different byte length does not change independent-header ownership.
        'S_other = S[.STRINGDATA[1] = $ptascii("other")][.STORE[n_bystander] = DEFINED (PSTRING_CARRIER (REQUEST_STRING 1) ($ptascii("other")))]',
        '$string_carrier_valid(S_other, PSTRING_CARRIER (REQUEST_STRING 1) ($ptascii("other")))',
        '$string_read_cv_released(S_other, pkeyread)',
        '$string_read_resume(S_other, pstringread) = S_other[.TODO = ptask_tail*][.RESULT = KNOWN PNULL][.BASE = BASE_VALUE (KNOWN PNULL)]',
        # Hidden owners remain outside this finite cell-only provider contour.
        'S_stack = S[.ERRORHANDLERS = S.ERRORHANDLERS ++ [{CALLBACK (pkeyread.BASE), LEVELS 0}]]',
        '~$string_read_provider_ready(S_stack, pstringread)',
        '~$string_read_cv_released(S_stack, pkeyread)',
        'PhpStep: S_stack ~> S_stack_refused',
        'S_stack_refused = S_stack[.COMPLETION = UNSUPPORTED "string offset borrowed carrier after callback"]',
        'S_array = S[.ARRAYS = [$array_insert($array_empty(), KINT 0, DIRECT pkeyread.BASE)]][.ALLOCATIONS = S.ALLOCATIONS ++ [HARRAY 0]][.HELD = [HARRAY 0]]',
        '$heap_valid($heap_graph(S_array))',
        '$heap_owners($heap_graph(S_array), HARRAY 0) = 1',
        '~$string_read_cv_released(S_array, pkeyread)',
        '~$string_read_cv_released(S[.RESULT = KNOWN pkeyread.BASE], pkeyread)',
        '~$string_read_cv_released(S[.BASE = BASE_VALUE (KNOWN pkeyread.BASE)], pkeyread)',
        '~$string_read_cv_released(S[.ASSERTCALLBACK = (pkeyread.BASE)], pkeyread)',
        'S_owned_tail = S[.TODO = (STRING_READ_RESULT pstringread) :: (CONCAT_RIGHT (KNOWN pkeyread.BASE) false false 29) :: ptask_tail*]',
        '~$string_read_cv_released(S_owned_tail, pkeyread)',
        '~$string_read_cv_released(S[.COMPLETION = BUDGET], pkeyread)',
        '~$string_read_cv_released(S[.TODO = (THROW_SEARCH 0) :: ptask_tail*], pkeyread)',
        '~$string_read_cv_released(S[.TODO = (STRING_READ_RESULT pstringread[.PHASE = STRING_BOUNDS 8]) :: ptask_tail*], pkeyread)',
        '~$string_read_cv_released(S, pkeyread[.PHASE = KEY_NULL])',
        '~$string_read_cv_released(S, pkeyread[.OWNERS = BASE_VALUE (KNOWN pkeyread.BASE)])',
    ]
    return (HELPERS + '\ndec $main() : bool\ndef $main() = true\n' + ''.join(
        '  -- ' + (check if check.startswith('PhpStep:') else 'if ' + check) + '\n'
        for check in checks), len(checks), len(checks) - derived_start)
