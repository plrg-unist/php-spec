"""An actual prior callback owns the old header after a normal CAST callback."""
import json

from string_offset_request_release_prior_cv_peer_review import HELPERS, seek
from string_offset_undefined_cv_review import guards

HELPERS = HELPERS.replace('pstringread.READ.PHASE = KEY_CV', 'pstringread.READ.PHASE = KEY_NULL')


def render(program, filename_b64):
    checks = [
        'S_initial = $php_run(' + program + ', 0, ' + json.dumps(filename_b64) + ')',
        'S_initial.COMPLETION = BUDGET',
    ] + seek('S_initial', 0, 'S_before') + [
        'S_before.TODO = (ERROR_HANDLER_INVOKE perrorcall) :: ptask_tail*',
        'perrorcall.RESUME = STRING_READ_RESULT pstringread',
        'pstringread = {READ pkeyread, BASECELL (n_original), KEYCELL (n_key), PHASE STRING_CAST}',
        r'pkeyread.PHASE = KEY_NULL /\ pkeyread.VALUE = PBOOL false',
        'pkeyread.NAME = eps',
        'pkeyread.INPUT = VARIABLE ($ptascii("key")) 21',
        'pkeyread.LINE = 21',
        'pkeyread.BASE = PSTRING_CARRIER (REQUEST_STRING 0) ($ptascii("abc"))',
        'pkeyread.OWNERS = BASE_VALUE (VARIABLE n_base_name* z_base)',
        'n_base_name* = $ptascii("base")',
        r'n_original = 2 /\ n_key = 3',
        '$lookup(S_before.ENV, n_base_name*) = (n_original)',
        '$lookup(S_before.ENV, $ptascii("key")) = (n_key)',
        'S_before.STORE[n_original] = DEFINED pkeyread.BASE',
        'S_before.STORE[n_key] = DEFINED (PBOOL false)',
        '$lookup(S_before.ENV, $ptascii("got")) = (n_got)',
        'n_got = 4',
        'pvalue_current = PSTRING_CARRIER INTERNED_STRING ($ptascii("requestCastCurrent"))',
        'perrorcall.CALLBACK = pvalue_current',
        'perrorcall.MESSAGE = $ptascii("String offset cast occurred")',
        'S_before.ERRORHANDLER = {CALLBACK (pvalue_current), LEVELS 30719}',
        'S_before.ERRORHANDLERS = [{CALLBACK (pkeyread.BASE), LEVELS 2}, {CALLBACK eps, LEVELS 0}]',
        '$error_call_valid(S_before, perrorcall)',
        '$string_read_source(S_before, pstringread)',
        '$string_read_provider_ready(S_before, pstringread)',
        '~$string_read_callback_cast_retained(S_before, pstringread)',
        'H_before = $heap_graph(S_before)',
        'H_before = {NODES ([HCELL 0, HCELL 1, HCELL 2, HCELL 3, HCELL 4]), EDGES eps, ROOTS ([HCELL 4, HCELL 3, HCELL 2, HCELL 1, HCELL 0]), DEBTS eps}',
        *guards('S_before'),
    ] + seek('S_before', 1, 'S') + [
        'S.TODO = (STRING_READ_RESULT pstringread) :: ptask_tail*',
        r'S.CURRENT = eps /\ S.FRAMES = eps',
        'S.STORE[n_original] = DEFINED pkeyread.BASE',
        '~((HCELL n_original) <- S.ALLOCATIONS)',
        '$lookup(S.ENV, n_base_name*) = (n_base)',
        'n_base = 10',
        '$lookup(S.ENV, $ptascii("key")) = (n_key)',
        'S.STORE[n_base] = DEFINED (PINT 99)',
        'S.STORE[n_key] = DEFINED (PINT 0)',
        'S.STORE[n_got] = DEFINED (PINT 99)',
        'S.REFCELLS = [n_base]',
        '$call_reference_operand_valid(S, REFERENCE n_base)',
        'S.STRINGDATA = [$ptascii("abc")]',
        'S.ERRORHANDLER = S_before.ERRORHANDLER',
        'S.ERRORHANDLERS = S_before.ERRORHANDLERS',
        '$error_handler_callable(S, pkeyread.BASE) = (true)',
        '$error_handler_retained(S, pkeyread.BASE)',
        '$error_handler_roots(S.ERRORHANDLER) = eps',
        '$error_handler_stack_roots(S.ERRORHANDLERS) = eps',
        '$string_read_source(S, pstringread)',
        '~$string_read_retained(S, pstringread, S.ENV)',
        '~$string_read_callback_retained(S, pstringread)',
        '$string_read_callback_cast_retained(S, pstringread)',
        '$string_read_provider_ready(S, pstringread)',
        '~$string_read_cv_released(S, pkeyread)',
        '$string_read_key_current(S, pstringread) = (PINT 0)',
        '$string_read_key_capture(S, pkeyread.INPUT, pkeyread.BASE) = ((PINT 0, pstringread.KEYCELL))',
        '$task_nodes(STRING_READ_RESULT pstringread) = eps',
        'H = $heap_graph(S)',
        'H = {NODES ([HCELL 0, HCELL 1, HCELL 3, HCELL 4, HCELL 10]), EDGES eps, ROOTS ([HCELL 10, HCELL 4, HCELL 3, HCELL 1, HCELL 0]), DEBTS eps}',
        '$heap_owners(H, HCELL n_original) = 0',
        *guards('S'),
        'S_expected = S[.TODO = ptask_tail*][.RESULT = KNOWN (PSTRING_CARRIER INTERNED_STRING ([97]))][.BASE = BASE_VALUE (KNOWN PNULL)]',
        'PhpStep: S ~> S_after',
        'S_after = S_expected',
        '$heap_graph(S_after) = H',
        'S_after.EVENTS = S.EVENTS',
        '$drive_steps(S, 0) = S[.COMPLETION = BUDGET]',
        '$drive_steps(S, 1) = S_expected[.COMPLETION = BUDGET]',
        *guards('S_after'),
    ]
    derived_start = len(checks)
    checks += [
        'S_current = S[.ERRORHANDLER = {CALLBACK (pkeyread.BASE), LEVELS 0}][.ERRORHANDLERS = eps]',
        '$string_read_callback_cast_retained(S_current, pstringread)',
        'S_deep = S[.ERRORHANDLERS = [{CALLBACK eps, LEVELS 9}, {CALLBACK (pvalue_current), LEVELS 0}, {CALLBACK (pkeyread.BASE), LEVELS $(-1)}]]',
        '$string_read_callback_cast_retained(S_deep, pstringread)',
        '$string_read_resume(S_deep, pstringread) = S_deep[.TODO = ptask_tail*][.RESULT = S_expected.RESULT][.BASE = S_expected.BASE]',
        # Ownership never substitutes for the separately captured key location.
        'S_moved = S[.ENV = (BIND ($ptascii("key")) n_base) :: $unbind(S.ENV, $ptascii("key"))]',
        '$string_read_callback_cast_retained(S_moved, pstringread)',
        '$string_read_provider_ready(S_moved, pstringread)',
        '$string_read_key_current(S_moved, pstringread) = eps',
        '$string_read_resume(S_moved, pstringread) = S_moved[.COMPLETION = UNSUPPORTED "string offset changed key locator after callback"]',
        # No closed-death authority is introduced for KEY_NULL by a failed owner.
        'S_absent = S[.ERRORHANDLERS = eps]',
        '~$string_read_callback_cast_retained(S_absent, pstringread)',
        '~$string_read_provider_ready(S_absent, pstringread)',
        '~$string_read_cv_released(S_absent, pkeyread)',
        '$string_read_resume(S_absent, pstringread) = S_absent[.COMPLETION = UNSUPPORTED "string offset borrowed carrier after callback"]',
        'pvalue_other = PSTRING_CARRIER (REQUEST_STRING 1) ($ptascii("abc"))',
        'S_other = S[.STRINGDATA = S.STRINGDATA ++ [$ptascii("abc")]][.ERRORHANDLERS = [{CALLBACK (pvalue_other), LEVELS 2}]]',
        '$string_carrier_valid(S_other, pvalue_other)',
        '$error_handler_callable(S_other, pvalue_other) = (true)',
        '$string_same(pvalue_other, pkeyread.BASE) = (false)',
        '~$string_read_callback_cast_retained(S_other, pstringread)',
        '~$string_read_provider_ready(S_other, pstringread)',
        '~$string_read_cv_released(S_other, pkeyread)',
        'S_raw = S[.ERRORHANDLERS = [{CALLBACK (PSTRING ($ptascii("abc"))), LEVELS 2}]]',
        '~$string_read_callback_cast_retained(S_raw, pstringread)',
        'S_unknown = S[.ERRORHANDLERS = [{CALLBACK (pvalue_other), LEVELS 2}]]',
        '~$string_read_callback_cast_retained(S_unknown, pstringread)',
        'S_bad_bytes = S[.ERRORHANDLERS = [{CALLBACK (PSTRING_CARRIER (REQUEST_STRING 0) ($ptascii("abd"))), LEVELS 2}]]',
        '~$string_read_callback_cast_retained(S_bad_bytes, pstringread)',
        'S_uncallable = S[.FUNCTIONS = eps][.CALLABLES = eps]',
        '~$string_read_callback_cast_retained(S_uncallable, pstringread)',
        '~$string_read_callback_cast_retained(S[.TODO = ptask_tail*], pstringread)',
        'S_pending = S[.TODO = (THROW_SEARCH 0) :: ptask_tail*]',
        '~$string_read_callback_cast_retained(S_pending, pstringread)',
        '~$string_read_provider_ready(S_pending, pstringread)',
        '$string_read_discard(S_pending, pstringread) = S_pending[.COMPLETION = UNSUPPORTED "string offset borrowed carrier after callback"]',
        '~$string_read_callback_cast_retained(S[.COMPLETION = THROWING 0], pstringread)',
        '~$string_read_callback_cast_retained(S[.COMPLETION = EXITED 23], pstringread)',
        '~$string_read_callback_cast_retained(S[.COMPLETION = BUDGET], pstringread)',
        '~$string_read_callback_cast_retained(S, pstringread[.PHASE = STRING_LEADING 0])',
        '~$string_read_callback_cast_retained(S, pstringread[.PHASE = STRING_BOUNDS 8])',
        '~$string_read_callback_cast_retained(S, pstringread[.READ.PHASE = KEY_CV])',
        '~$string_read_callback_cast_retained(S, pstringread[.BASECELL = eps])',
        '~$string_read_callback_cast_retained(S, pstringread[.KEYCELL = eps])',
    ]
    for field in ('ORIGIN', 'SOURCES', 'CODE', 'STRINGDATA'):
        checks.append('~$string_read_callback_cast_retained(S[.' + field + ' = eps], pstringread)')
    return (HELPERS + '\ndec $main() : bool\ndef $main() = true\n' + ''.join(
        '  -- ' + (check if check.startswith('PhpStep:') else 'if ' + check) + '\n'
        for check in checks), len(checks), len(checks) - derived_start)
